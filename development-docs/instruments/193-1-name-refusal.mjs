// ПРИВЕДЕНИЕ ИМЕНИ ПРОТИВ ЕГО ПОЧИНКИ (193-1, найдено измерением).
//
// 🔒 ЗАКОННО менять форму одного и того же имени: регистр, пробелы, дефисы.
// 🛑 НЕЗАКОННО вычёркивать знаки, которых в имени быть не должно: пришло не имя,
// и вычеркнув лишнее, мы заведём в живой таблице человека колонку с
// бессмысленным именем — навсегда.
//
// Запуск: node development-docs/instruments/193-1-name-refusal.mjs

import { normalizeName } from "../../lib/naming.mjs"

const CASES = [
  ["people he calls his friends", true, "пробелы — законное приведение"],
  ["People-He-Met-At-The-Fair", true, "дефисы и регистр — законное приведение"],
  ["city_where_he_lives_now", true, "уже по стандарту"],
  ["probe_193_x; DROP TABLE person_who_owns_this_project", false, "точка с запятой — не имя"],
  ["field.money; DROP TABLE tgdesk_messages", false, "точка и SQL — не имя (случай шага 81)"],
  ["name'); --", false, "кавычка, скобка, комментарий SQL"],
  ["города где он жил", false, "чужой алфавит — имя уезжает в SQL, белый список его не пропускает"],
  ["ab", false, "короче трёх знаков"],
  // 🔒 ГРАНИЦА ОТВЕТСТВЕННОСТИ, И ОНА ЗДЕСЬ ЖЕ ИЗМЕРЕНА: этот разбор отвечает
  // за ЗНАКИ, а не за смысл. «Ярлык вместо фразы» ловит проверка четырёх слов в
  // `scripts/agent/memory-tools.mjs`, и правильно: сведи мы обе проверки сюда,
  // одно правило оказалось бы в двух местах.
  // ✗ Ожидание «отказ» стояло здесь по моей ошибке и было исправлено ПОСЛЕ
  // прогона — в пользу кода, потому что довод написан в самом случае, а не
  // придуман под результат.
  ["friend", true, "одно слово: по знакам годно; ярлык ловит проверка четырёх слов в руке"],
]

let bad = 0
console.log("===NAME_REFUSAL===")
for (const [raw, shouldPass, why] of CASES) {
  const got = normalizeName(raw)
  const ok = shouldPass ? got !== "" : got === ""
  if (!ok) bad += 1
  console.log(`${ok ? "✓" : "✗"} ${(got || "«отказ»").padEnd(34)} ← ${JSON.stringify(raw).slice(0, 56)} · ${why}`)
}
console.log(bad === 0 ? "✓ OK" : `✗ ПРОВАЛ: ${bad}`)
