/** Языки службы. Список здесь единственный — второй разошёлся бы молча. */
const SUPPORTED = ["ru", "en"];

export async function proxy(request: NextRequest) {
  const { pathname } = new URL(request.url);

  if (SELF_GUARDED.has(pathname)) {
    return NextResponse.next();
  }

  // ✗ ЭТОТ БЛОК Я ВЫБРОСИЛ ПРИ КОПИРОВАНИИ КАК «ЛИШНИЙ», И ЭТО СЛОМАЛО ВХОД
  // ЦЕЛИКОМ. Нашёл владелец 2026-09-10: «я не могу войти, никакое модальное окно
  // входа не появляется». Механизм отказа:
  //   ① шапка (скопированная как есть) ссылается на ОТНОСИТЕЛЬНЫЕ `/login?lang=`
  //      и `/logout?lang=` — она не знает адреса службы входа и знать не должна;
  //   ② без этого правила `/login` уходил в Next и совпадал с динамическим
  //      сегментом `[lang]` — то есть открывалась ГЛАВНАЯ с языком «login»,
  //      отчего на русском адресе показывался английский текст.
  // 🔒 УРОК ШИРЕ СЛУЧАЯ: «лишнее» в привратнике определяется НЕ ПО НЕМУ САМОМУ.
  // Правило выглядит чужим, пока не увидишь, кто на него ссылается, — а
  // ссылается разметка, лежащая в другом файле и не упоминающая привратника.
  // Копируя экран, копируй и правила, которыми он держится.
  if (pathname === "/login" || pathname === "/register" || pathname === "/logout") {
    const search = new URLSearchParams(new URL(request.url).search);
    if (pathname === "/logout" && !search.has("redirectUrl")) {
      // 🔒 ЯЗЫК БЕРЁТСЯ ИЗ ТОГО, ЧТО ПРИСЛАЛ ОСТРОВОК, А НЕ ИЗ АДРЕСА ВЫХОДА.
      // У `/logout` языкового сегмента нет по устройству, и `langOf()` там падает
      // на заголовок браузера — русского человека выход возвращал бы на
      // английскую главную.
      const asked = search.get("lang") ?? "";
      const back = SUPPORTED.includes(asked) ? asked : langOf(request);
      // 🔒 ПОСЛЕ ВЫХОДА — СТРАНИЦА ПРИВЕТСТВИЯ, А НЕ ГЛАВНАЯ (179-1, слово
      // владельца 2026-09-10: «after success logout to do welcome page»). Там две
      // дороги — войти снова или вернуться на главную; главная сама по себе не
      // говорит человеку, что он только что вышел.
      search.set("redirectUrl", `${publicOrigin(request)}/${back}/welcome`);
    }
    const qs = search.toString();
    const away = NextResponse.redirect(
      `${publicAuthOrigin(request)}${pathname}${qs ? `?${qs}` : ""}`,
    );

    // 🛑 ВЫХОД ЧИСТИТ КУКУ И НА НАШЕМ ХОСТЕ — БЕЗ ЭТОГО ОН НЕ РАБОТАЕТ ВОВСЕ.
    // ✗ У чата это оплачено тремя кругами отладки 2026-09-07, и нашёл это
    // владелец: «на 3000 сессию потерял, а в чате всё ещё горит авторизация».
    // Кук ДВЕ: общая с `Domain=.<апекс>` и host-only на нашем хосте. Служба входа
    // вторую вычистить не может физически — браузер не даёт одному хосту стирать
    // куки другого. Значит это НАША обязанность, и ничья больше.
    // 🔒 ЧИСТИМ ВСЕ ИМЕНА, А НЕ ОДНО: режимы дают разные префиксы, старые версии
    // библиотеки — другое имя целиком. Кука, не попавшая в список, оставит
    // человека внутри, и выглядеть это будет как «выход не работает» без ошибок.
    if (pathname === "/logout") {
      for (const name of [
        "__Secure-authjs.session-token",
        "authjs.session-token",
        "__Secure-next-auth.session-token",
        "next-auth.session-token",
      ]) {
        // 🛑 ПРЕФИКС `__Secure-` ТРЕБУЕТ ФЛАГА `Secure`, ИНАЧЕ БРАУЗЕР ОТКЛОНЯЕТ
        // УСТАНОВКУ МОЛЧА — и очистка не происходит. Заголовок в ответе и
        // применённая кука — разные утверждения.
        away.cookies.set(name, "", {
          httpOnly: true,
          maxAge: 0,
          path: "/",
          sameSite: "lax",
          secure: name.startsWith("__Secure-"),
        });
      }
    }
    return away;
  }

  // 🔒 РОДНЫЕ МАРШРУТЫ NextAuth ШАБЛОНА ОСТАВЛЕНЫ ЖИВЫМИ — сносить чужой
  // механизм ради своего значит ссориться с каждым обновлением сверху.
  if (pathname.startsWith("/api/auth")) {
    return NextResponse.next();
  }

  if (PUBLIC_LANG_ROOTS.has(pathname)) {
    return NextResponse.next();
  }

  // 🔒 СТРАНИЦА ПРИВЕТСТВИЯ ОТКРЫТА БЕЗ ВХОДА (179-1): на неё приходят сразу
  // после выхода, то есть ровно тогда, когда сессии уже нет. Закрой её замком —
  // и человек, только что вышедший, был бы тут же отправлен на форму входа.
  // 🛑 ТОЧНЫМ СПИСКОМ, КАК ГЛАВНАЯ, А НЕ `endsWith("/welcome")`, как у чата:
  // окончание пропустило бы и `/ru/settings/welcome`, заведи его кто-нибудь.
  if (pathname === "/ru/welcome" || pathname === "/en/welcome") {
    return NextResponse.next();
  }

  // 🔒 ГОЛЫЙ КОРЕНЬ ПЕРЕАДРЕСУЕТСЯ НА ЯЗЫКОВОЙ, А НЕ ПРОПУСКАЕТСЯ.
  // ✗ оплачено у чата 2026-09-07: корень открыли, а страницы у него нет — все
  // живут под `[lang]`. Человек, набрав адрес службы без языка, получал `404`.
  // 🛑 И ЗДЕСЬ ЭТО ВАЖНЕЕ, ЧЕМ ТАМ: корень памяти занят СТАРОЙ страницей журнала
  // на голом Node, и она отвечает раньше Next. Переадресация до неё не доходит —
  // строка стоит на будущее, когда журнал уедет со своего корня целиком.
  if (pathname === "/") {
    return NextResponse.redirect(`${publicOrigin(request)}/${langOf(request)}`);
  }

  // 🛑 ПУСТАЯ КОРЗИНА КУК — НЕ ПОВОД НЕ СПРАШИВАТЬ, И ЭТО ПРО РЕЖИМ БЕЗ ДОМЕНА.
  // Пока сервер живёт на голом IP, служба входа отдаёт архитектора ВСЕМ: панель
  // и сайт в онбординге работают, и память не имеет права быть единственной, кто
  // отвечает «войдите» там, где входить ещё некуда. Цена — один запрос по петле.
  const cookie = request.headers.get("cookie") ?? "";
  let signedIn = false;
  try {
    const authService =
      process.env.AUTH_SERVICE_URL ||
      process.env.NEXT_PUBLIC_AUTH_URL ||
      "http://127.0.0.1:3001";
    const res = await fetch(`${authService}/api/session`, {
      cache: "no-store",
      headers: cookie ? { cookie } : undefined,
    });
    // 🔒 ОТВЕТ ЧИТАЕТСЯ ЦЕЛИКОМ, А НЕ ПО КОДУ: `200` с телом без `email` значит
    // «никто не вошёл», а не «вошёл безымянный».
    signedIn = res.ok && Boolean(((await res.json()) as { email?: string })?.email);
  } catch {
    // 🛑 СЛУЖБА ВХОДА МОЛЧИТ — ЧЕЛОВЕК НЕ УЗНАН, И ЭТО ЧЕСТНЫЙ ИСХОД. Пускать
    // «на всякий случай» значило бы открыть страницу целиком в тот момент, когда
    // одна служба не отвечает.
    signedIn = false;
  }

  if (!signedIn) {
    // 🔒 УВОДИМ К ЕДИНСТВЕННОЙ ТОЧКЕ ВХОДА, А НЕ К СВОЕЙ ЗАГЛУШКЕ. У чата
    // заглушка `/welcome` есть и объясняет, где человек оказался; у памяти её
    // нет, и заводить её ради одного случая значило бы завести вторую страницу
    // о входе — при том что вход в проекте один.
    //
    // ✗ ПЕРВАЯ РЕДАКЦИЯ БРАЛА ВНУТРЕННИЙ АДРЕС, И ЭТО ИЗМЕРЕНО ЖИВЬЁМ 2026-09-10:
    // человек получал `307` на `http://127.0.0.1:3001/login?callbackUrl=
    // https://localhost:3700/...` — то есть его отправляли на адрес, которого в
    // его браузере не существует. За nginx `request.url` всегда петля; публичное
    // имя приходит ТОЛЬКО заголовками `x-forwarded-*`.
    const back = `${publicOrigin(request)}${pathname}`;
    return NextResponse.redirect(
      `${publicAuthOrigin(request)}/login?callbackUrl=${encodeURIComponent(back)}&requireRole=architect`,
    );
  }

  return NextResponse.next();
}

// 🔒 ЯЗЫК ДЛЯ ПЕРЕАДРЕСАЦИИ БЕРЁТСЯ ИЗ САМОГО АДРЕСА, А НЕ ЗАШИТ. Увести
// русского на английскую главную значит показать чужой язык в первый же момент,
// когда он ещё не вошёл и объяснить некому.
// 🛑 СПИСКА ЯЗЫКОВ ЗДЕСЬ НЕТ НАМЕРЕННО: второй список рядом с настоящим
// разошёлся бы с ним молча. Берём первый сегмент, если он похож на код языка,
// иначе смотрим заголовок браузера, иначе английский. Приём взят у чата.
function langOf(request: NextRequest): string {
  const first = new URL(request.url).pathname.split("/")[1] ?? "";
  if (/^[a-z]{2}$/.test(first)) {
    return first;
  }
  const accept = request.headers.get("accept-language") ?? "";
  return accept.toLowerCase().startsWith("ru") ? "ru" : "en";
}

