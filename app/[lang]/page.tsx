import { memoryUi } from "./settings/_i18n/memory.i18n";

const LANGS = ["ru", "en"] as const;

// ГЛАВНАЯ СТРАНИЦА СЛУЖБЫ ПАМЯТИ — ПУБЛИЧНАЯ (178-5).
//
// 🎯 РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-10, ДОСЛОВНО: «создай главную страницу, которая
// будет доступна без авторизации, пока минимальная заглушка как у чата, тоже
// мультиязычные».
//
// 🪦 СКОПИРОВАНА С ГЛАВНОЙ СЛУЖБЫ ЧАТА (`app/[lang]/page.tsx`, 156-1) — та же
// роль, та же форма, тот же довод. Разница одна: текст здесь берётся из словаря,
// а не написан в разметке. У чата он строкой, потому что там было «пока без
// какого-либо дизайна»; здесь владелец сразу попросил мультиязычность.
//
// 🔒 ЭТО СМЕНА АРХИТЕКТУРЫ ВХОДА, А НЕ ПРОСТО ЕЩЁ ОДНА СТРАНИЦА. До неё служба
// была закрыта ЦЕЛИКОМ: любой неузнанный запрос уводился к форме входа, и
// снаружи не существовало ни одной поверхности — то есть на вопрос «куда войти»
// у самой службы ответа не было. Теперь ответ виден: вот главная, вот вход в
// шапке, всё остальное — за ним.
//
// 🔒 ЧТО НЕ ПОМЕНЯЛОСЬ: своего входа у памяти НЕТ и не будет. Кнопка в шапке
// ведёт в единственную службу `:3001`, кука доменная, и все службы видят
// человека одинаково. Публичной стала одна страница, а не авторизация.
//
// 🔒 НАБОР ЯЗЫКОВ ОБЪЯВЛЯЕТСЯ, И БЕЗ ЭТОГО СБОРКА ПАДАЕТ — урок оплачен дважды:
// у чата 2026-09-06 и здесь же сегодня. Пока значения динамического сегмента
// неизвестны, Next не собирает даже оболочку и пишет «Uncached data was accessed
// outside of <Suspense>» — текст, который на причину не указывает вовсе.
export function generateStaticParams() {
  return LANGS.map((lang) => ({ lang }));
}

export default async function MemoryHome({
  params,
}: {
  params: Promise<{ lang: string }>;
}) {
  const { lang } = await params;
  const ui = memoryUi(lang);

  return (
    <main className="mx-auto flex max-w-3xl flex-col gap-4 px-6 py-16" data-public-home>
      <h1 className="font-semibold text-[length:var(--fs-h1)]">{ui.title}</h1>
      <p className="text-muted-foreground">{ui.subtitle}</p>
      <p className="text-muted-foreground">{ui.home.whatIsBehind}</p>
      {/* 🔒 КНОПОК ЗДЕСЬ НЕТ: ВХОД И АККАУНТ ЖИВУТ В ШАПКЕ — тот же довод, что у
          чата (156-2). Вторая пара кнопок на странице спорила бы с шапкой за то,
          какая из них правда, и однажды они разошлись бы состоянием. */}
      <p className="text-[length:var(--fs-small)] text-muted-foreground">{ui.home.whereToEnter}</p>
    </main>
  );
}
