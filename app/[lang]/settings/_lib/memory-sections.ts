export const MEMORY_SECTIONS = [
  // 🪦 «Паспорт» снят 208-3 вместе со своим документом (решение владельца 2026-09-16): то, что он
  // объяснял, живёт в инструкции службы и на её главной. Первым разделом стал «API».
  "api",
  "memory-test",
  "graph-test",
  "vector-test",
  "object-test",
  "link-test",
  "journal",
  "openai",
  "settings",
] as const;

export type MemorySection = (typeof MEMORY_SECTIONS)[number];

export function isMemorySection(v: unknown): v is MemorySection {
  return typeof v === "string" && (MEMORY_SECTIONS as readonly string[]).includes(v);
}

/**
 * Какой раздел открыт.
 *
 * 🔒 НЕИЗВЕСТНОЕ ЗНАЧЕНИЕ ПАДАЕТ НА ПЕРВЫЙ РАЗДЕЛ (с 208-3 это «API»), А НЕ НА ПУСТОЙ ЭКРАН. Адрес
 * приходит из строки браузера, то есть от кого угодно; «нет такого раздела»
 * человек читает как поломку проекта, а не как свою опечатку.
 */
export function resolveMemorySection(raw: string | undefined): MemorySection {
  return isMemorySection(raw) ? raw : "api";
}

/** Адрес раздела. */
export function hrefOfMemorySection(lang: string, section: MemorySection): string {
  return `/${lang}/settings?section=${section}`;
}
