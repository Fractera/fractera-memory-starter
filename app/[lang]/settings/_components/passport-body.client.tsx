"use client"

import remarkGfm from "remark-gfm"
import { Streamdown } from "streamdown"
import { remarkPassportAnchors, remarkPassportMarks } from "../_lib/passport-marks"

// ТЕЛО ПАСПОРТА ПАМЯТИ: ТЕКСТ С MARKDOWN-РАЗМЕТКОЙ (182-1).
//
// 🎯 ПОРЯДОК РАБОТЫ, НАЗВАННЫЙ ВЛАДЕЛЬЦЕМ 2026-09-10: «сначала обсуждаем затем
// создаем элемент в паспорте я читаю утверждаю или изменяю потом делаем строчку
// для инструкции». Значит паспорт — не отчёт о сделанном, а место, где замысел
// живёт ДО кода, и читает его человек глазами на этой странице.
//
// 🔒 ПРИЁМЫ ВЗЯТЫ У ПАСПОРТА ЧАТА ЦЕЛИКОМ, А НЕ ИЗОБРЕТЕНЫ ЗАНОВО: там они
// оплачены двумя дефектами, найденными владельцем. Здесь короче ровно на один
// слой — у памяти нет вендоренной библиотеки чата, поэтому разметчик зовётся
// прямо, теми же настройками.
//
// 🛑 `remarkGfm` ОБЯЗАТЕЛЕН, И ЭТО ОПЛАЧЕНО СЛОМАННЫМ ПАСПОРТОМ ЧАТА. Переданный
// список `remarkPlugins` **заменяет** умолчание разметчика, а в умолчании живёт
// GFM — то есть таблицы. Порядок важен: GFM первым, наши плагины после него.
//
// 🛑 `allowedTags={{ u: [] }}` ОБЯЗАТЕЛЕН, И БЕЗ НЕГО ПОДСВЕТКА НЕ РАБОТАЕТ
// НИКОГДА. `Streamdown` санирует дерево схемой `hast-util-sanitize`, и `u` в неё
// не входит: плагин верно строит `<u>`, а санитайзер молча его снимает, оставляя
// голый текст. `allowedTags` — единственная официальная дверь для расширения
// списка тегов.
//
// 🛑 СЫРОЙ HTML В ЭТОМ ДОКУМЕНТЕ НЕ РАБОТАЕТ — ни `<mark>`, ни `<a id="…">`: они
// доехали бы до страницы буквами. Поэтому и подсветка, и якорь ставятся в ДЕРЕВЕ
// разметки (`passport-marks.ts`), а не строкой в тексте.

export function PassportBody({ text }: { text: string }) {
  return (
    <article className="max-w-none" data-passport-text>
      <Streamdown
        allowedTags={{ u: [] }}
        className="size-full [&>*:first-child]:mt-0 [&>*:last-child]:mb-0"
        remarkPlugins={[remarkGfm, remarkPassportMarks, remarkPassportAnchors]}
      >
        {text}
      </Streamdown>
    </article>
  )
}
