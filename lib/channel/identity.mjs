//
// 🛑 ВТОРОГО ИСТОЧНИКА ИМЕНИ НЕ ЗАВОДИТСЯ. Напиши мы название словом рядом — два имени разошлись бы
// на первой же правке реестра, и починил бы это только тот, кто заметил.

import { readdirSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { OWN_PROPS } from "../services.mjs"
import { ME } from "../state.mjs"

/**
 * Корень службы. Всё состояние канала лежит ВНУТРИ него — служба уносит свой канал с собой.
 *
 * 🛑 ПЕРЕМЕННАЯ НАЗВАНА ПО РОЛИ (`SERVICE_ROOT`), А НЕ ПО СЛУЖБЕ. Рядом живёт унаследованная
 * `MEMORY_BUILD_ROOT` — её читает писатель заявок, и трогать чужой контракт этот шаг не вправе; но
 * заводить её имя ЗДЕСЬ значило бы протащить имя службы в код, который завтра переедет в другую.
 */
export const serviceRoot = () => process.env.SERVICE_ROOT ?? process.cwd()

/** Идентификатор службы: тот же, которым она зовётся в реестре. */
export const serviceId = () => ME

/** Запись службы в общем реестре. Пусто — служба не названа там, и это само по себе дефект. */
export function serviceEntry() {
  // 🔒 227-3: ЧЕРЕЗ ШОВ, А НЕ МИМО НЕГО. Раньше здесь читался общий реестр напрямую — единственное
  // место в службе, ходившее в файл в обход `lib/services.mjs`. Такая утечка переживает любой
  // переезд источника молча: шов уже спрашивает панель, а этот код всё ещё открывает файл, которого
  // нет.
  return OWN_PROPS
}

/**
 * Человеческое название службы.
 *
 * 🔒 ПОРОЖДАЕТСЯ, А НЕ ПИШЕТСЯ: реестр хранит `id` и `subdomain`, отдельного «красивого имени» у него
 * нет — значит берём `id` и поднимаем первую букву. Появится в реестре поле названия — читаться будет
 * оно, и правка будет одна.
 */
export function serviceTitle() {
  const id = String(serviceEntry()?.subdomain ?? serviceId())
  return id.charAt(0).toUpperCase() + id.slice(1)
}

/**
 * Навык разработки этой службы — НАЙДЕННЫЙ, а не названный словом.
 *
 * ✗ Оплачено прибором переносимости в тот же час: в пусковом файле канала стояло `memory-development`,
 * и это было единственное место, где имя службы всё-таки просочилось. Превратите службу в рассылку —
 * и строитель получил бы команду открыть навык, которого у неё нет.
 * 🔒 ИЩЕТСЯ ПО РОЛИ: навык разработки — тот, чьё имя кончается на `-development`. Если таких окажется
 * несколько, открыт был бы первый попавшийся, а остальные расходились бы с ним молча — поэтому
 * найденный принимается только когда он один.
 * 🛑 НЕ НАШЁЛСЯ — ПУСТО, а не выдуманное имя: команда «открой навык, которого нет» хуже её отсутствия.
 */
export function developmentSkill() {
  try {
    const dir = join(serviceRoot(), ".claude", "skills")
    const found = readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isDirectory() && d.name.endsWith("-development"))
      .map((d) => d.name)
    return found.length === 1 ? found[0] : ""
  } catch {
    return ""
  }
}

/** Папка состояния канала: своя у каждой службы — иначе два бота на машине делили бы один токен. */
export const channelStateDir = (channel = "telegram") => join(serviceRoot(), ".channel", channel)

/** Имя сессии канала. Из идентификатора службы, а не из слова. */
export const channelSessionName = () => `${serviceId()}-channel`

/**
 * Случайный код в имя бота.
 *
 * 🎯 Мысль владельца: «CCID — идентификатор случайный, который позволит быть уверенным, что Telegram-боты
 * будут у каждого разные и конфликта внутри инфраструктуры Telegram не возникнет».
 * 🛑 КОД НЕ ХРАНИТСЯ И НИ НА ЧТО НЕ ВЛИЯЕТ: это подсказка человеку в BotFather, а не наш идентификатор.
 * Сохрани мы его — появилось бы второе имя службы, ровно то, чего этот шаг избегает.
 */
export const suggestedCcid = () => Math.random().toString(16).slice(2, 6)

/**
 * Две рекомендации для BotFather — их именно ДВЕ, и они разного рода.
 *
 * 🎯 Слово владельца 2026-09-17: «пробелы в названии точно не нужны, я как раз вместо пробелов
 * авторизовал дефисы… Telegram требует два названия… сделай две записи, чтобы людям было проще».
 *
 * 🔒 ПРАВИЛА ВЗЯТЫ У ПЕРВОИСТОЧНИКА, А НЕ ПО ПАМЯТИ (README плагина каналов, шаг «Create a bot»):
 *   · **Name** — видимое имя в шапке чата, может содержать что угодно;
 *   · **Username** — уникальная ручка, ОБЯЗАНА кончаться на `bot`, пример `my_assistant_bot`.
 * 🛑 ОТСЮДА РАЗНЫЕ РАЗДЕЛИТЕЛИ, И ЭТО НЕ ВКУС: в видимом имени стоят дефисы, как просил владелец, а в
 * ручке дефисов не бывает вовсе — там подчёркивания. Предложи мы дефис в ручке, Telegram отказал бы, и
 * человек решил бы, что ошибся сам.
 * 🛑 ДЛИНА РУЧКИ ОГРАНИЧЕНА 32 ЗНАКАМИ: длинное имя службы подрезается, иначе рекомендация заведомо
 * не примется.
 */
export const suggestedBotName = (ccid = suggestedCcid()) => `${serviceTitle()}-Fractera-${ccid}`

export function suggestedBotUsername(ccid = suggestedCcid()) {
  const clean = (s) => String(s).replace(/[^A-Za-z0-9]/g, "")
  const tail = `_Fractera_${clean(ccid)}_bot`
  const head = clean(serviceTitle()).slice(0, Math.max(3, 32 - tail.length))
  return `${head}${tail}`
}
