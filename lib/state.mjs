//   • РЕЕСТР говорит, КАК ЗАДУМАНО: субдомен, порт, род авторизации. Его правят
//     руками, он одинаков во всех службах (решение владельца: «руки в файле,
//     служба только читает»);
//   • САМ ЗАПРОС говорит, КАК ЕСТЬ: по домену пришли или по голому адресу, каким
//     протоколом, каким именем хоста.
// 🛑 РАСХОЖДЕНИЕ НАЗЫВАЕТСЯ, А НЕ ЧИНИТСЯ. Служба, молча подправившая реестр под
// себя, перестаёт быть тем, о чём договорились; служба, промолчавшая о
// расхождении, даёт человеку уверенный неверный ответ — а это дороже пустого.

import { NEIGHBOURS_KNOWN, OWN_PROPS, OWN_PROPS_ERROR } from "./services.mjs"

/** Имя этой службы в реестре. Оно вечное: на нём висят пути и проверки. */
export const ME = "memory"

/**
 * Каким потоком пришёл запрос.
 *
 * 🔒 ЭТО ИЗМЕРЕНИЕ, А НЕ НАСТРОЙКА. Замысел владельца: «ваш IP — незащищённый
 * поток, ваш домен — защищённый». Значит правду говорит не файл, а то, КАК
 * запрос доехал: имя хоста и протокол, которыми пользовался зовущий.
 * 🛑 ГОЛЫЙ АДРЕС СЧИТАЕТСЯ НЕЗАЩИЩЁННЫМ ДАЖЕ ПО HTTPS: сертификат на IP есть
 * редкое исключение, и обещать человеку защиту по одному лишь `https` — это
 * обещание, которое он проверит в свой худший день.
 */
export function streamOf({ host, proto }) {
  const name = String(host ?? "").split(":")[0]
  const isIp = /^\d{1,3}(\.\d{1,3}){3}$/.test(name) || name === "localhost" || name.startsWith("[")
  if (!name) return { secured: false, why: "имя хоста не пришло — зовущий не назвал, куда стучится" }
  if (isIp) return { secured: false, why: "зовут по адресу машины, а не по домену: поток незащищённый" }
  return {
    secured: String(proto ?? "").toLowerCase() === "https",
    why: String(proto ?? "").toLowerCase() === "https" ? "домен и https" : "домен есть, но протокол не https",
  }
}

/**
 * Состояние службы: кто я, где я, чем меня зовут и как в меня входят.
 *
 * @param {{host?: string, proto?: string}} seen — как ПРИШЁЛ этот запрос
 */
export function state({ host, proto } = {}) {
  // 🔒 227-3: «КТО Я» БЕРЁТСЯ ИЗ ОПИСАНИЯ СЕБЯ НА ДИСКЕ, А НЕ ИЗ ОБЩЕГО РЕЕСТРА. Служба обязана
  // отвечать на этот вопрос, даже когда рядом нет ни панели, ни соседей.
  const me = OWN_PROPS
  const stream = streamOf({ host, proto })
  const hostname = String(host ?? "").split(":")[0]

  // Домен выводится из имени хоста и субдомена реестра: `memory.aifa.dev` минус `memory.` — это домен.
  const sub = me?.subdomain ?? null
  const domain = sub && hostname.startsWith(`${sub}.`) ? hostname.slice(sub.length + 1) : hostname || null

  const mismatch = []
  if (!me) {
    mismatch.push(
      `описания себя нет или оно не проходит тип из ядра (${OWN_PROPS_ERROR ?? "причина не названа"}) — ` +
        `состояние названо по памяти кода, а не по договорённости: OWN-SERVICE-PROPS.json`,
    )
  }
  else if (sub && hostname && !hostname.startsWith(`${sub}.`) && !stream.why.startsWith("зовут по адресу")) {
    mismatch.push(`реестр обещает субдомен «${sub}», а запрос пришёл на «${hostname}»`)
  }

  return {
    ok: true,
    // кто я
    service: ME,
    auth: me?.auth ?? null,
    // 🔒 211-5: КОРЕНЬ — ЭТО ПРАВО ОТВЕЧАТЬ ПО ГОЛОМУ ДОМЕНУ, И ОНО У ОДНОЙ СЛУЖБЫ.
    // 🛑 227-3: НО ЭТО СВОЙСТВО СОБРАННОЙ КАРТЫ, А НЕ ОПИСАНИЯ СЕБЯ, И ХОЗЯИН ЕМУ — ПАНЕЛЬ. Служба,
    // объявившая себя корнем домена, объявила бы то, что решает не она. Пока карта не приходит
    // (227-5), честный ответ — «не знаю», а не `false`: `false` читается как «проверено, не я».
    root: NEIGHBOURS_KNOWN ? { holder: null, mine: false } : { holder: null, known: false },
    // где я — как задумано (реестр)
    planned: { api: me?.api ?? null, port: me?.port ?? null, subdomain: sub },
    // где я — как есть (этот запрос)
    seen: { domain, host: hostname || null, proto: proto ?? null, secured: stream.secured, why: stream.why },
    // 🔒 Расхождение между задуманным и увиденным называется вслух, а не сглаживается.
    mismatch,
    what_happened: mismatch.length
      ? `я ${ME}; поток ${stream.secured ? "защищённый" : "незащищённый"} (${stream.why}); ЕСТЬ РАСХОЖДЕНИЕ С РЕЕСТРОМ: ${mismatch.join("; ")}`
      : `я ${ME} на порту ${me?.port ?? "?"}, вход ${me?.auth ?? "?"}; поток ${stream.secured ? "защищённый" : "незащищённый"} (${stream.why})`,
  }
}
