/** Тишина, после которой разговор считается новым. Измерено: выше p90 пауз. */
export const NEW_SESSION_MS = 30 * 60 * 1000

/** С какого времени ответ считается добытым долгой цепочкой. Измерено: p75 всех ответов. */
export const LONG_CHAIN_MS = 8000

/**
 * Звать ли человека прокомментировать этот ответ.
 *
 * @param {{prevAt?: string|null, ms?: number, depthUsed?: number}} a
 * @returns {{invite: boolean, why: string}} — причина едет наружу полем `invited_because`:
 *   молчаливое решение нечем проверить, а проверять его придётся (закон о написанном законе).
 */
export function shouldInvite({ depthUsed = 0, ms = 0, prevAt = null } = {}) {
  const prev = prevAt ? Date.parse(prevAt) : NaN
  if (!Number.isFinite(prev)) return { invite: true, why: "first-ever" }
  if (Date.now() - prev >= NEW_SESSION_MS) return { invite: true, why: "session-start" }
  if (depthUsed > 1) return { invite: true, why: "deep-chain" }
  if (ms >= LONG_CHAIN_MS) return { invite: true, why: "long-chain" }
  return { invite: false, why: "mid-session-cheap" }
}
