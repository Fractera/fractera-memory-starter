// ДВА МЕТОДА О САМОЙ СЛУЖБЕ: ЧТО ОНА ДЕЛАЛА И «ЗАБУДЬ, ЧТО ДЕЛАЛА» (177-2).
//
// 🔒 ОНИ ОТЛИЧАЮТСЯ ОТ ОСТАЛЬНЫХ ПРЕДМЕТОМ, А НЕ УСТРОЙСТВОМ. `remember` и
// `recall` отвечают о ЧЕЛОВЕКЕ; эти два — о САМОЙ ПАМЯТИ. Путать нельзя:
// `recall` говорит, что память ЗНАЕТ, `journal` — что она ДЕЛАЛА.
//
// 🔒 ЖИВУТ ОТДЕЛЬНО ОТ `verbs.mjs`, И ЭТО НЕ ВКУС. Там глаголы о человеке, и
// они зовут журнал; будь исполнители журнала там же, файл начал бы звать сам
// себя — а разные предметы в одном файле рано или поздно смешиваются в коде.

import { clear, JOURNAL_PATH, readAll } from "./journal.mjs"
import { say } from "./words.mjs"

/**
 * Что память делала — её собственный рассказ, обычным текстом.
 *
 * 🔒 ОТДАЁМ ДОКУМЕНТ ЦЕЛИКОМ, БЕЗ ОТБОРА И БЕЗ ПЕРЕСКАЗА. Отбор здесь означал
 * бы, что служба решает, какая часть её работы достойна показа, — то есть тот
 * самый пересказ себя, из-за которого закон 143 запретил верить агенту на слово
 * о собственной работе.
 *
 * 🛑 ПУСТОЙ ДОКУМЕНТ — НЕ ОШИБКА, И ОТВЕТ ГОВОРИТ ЭТО СЛОВАМИ. «Записей нет» и
 * «журнал недоступен» — разные состояния, и путать их значит показывать
 * уверенную ложь: человек прочтёт пустоту как «память ничего не делала».
 */
export async function journal({ lang } = {}) {
  const text = await readAll()
  const entries = (text.match(/^## /gm) ?? []).length
  return {
    bytes: Buffer.byteLength(text, "utf8"),
    entries,
    ok: true,
    text,
    what_happened: entries
      ? say("journal-entries", lang, { n: entries })
      : say("journal-empty", lang),
    // 🔒 ПУТЬ НАЗЫВАЕТСЯ, ПОТОМУ ЧТО У ДОКУМЕНТА ДВА ЧИТАТЕЛЯ. Человек читает
    // страницу, агент — файл; не назвав файл, мы заставили бы его искать.
    where: JOURNAL_PATH,
  }
}

/**
 * Стереть рассказ памяти о своей работе.
 *
 * 🛑 ЗНАНИЕ О ЛЮДЯХ ЭТИМ НЕ ЗАТРАГИВАЕТСЯ, И ЭТО СКАЗАНО В ОТВЕТЕ. Метод с
 * названием «забудь» рядом с памятью обязан объяснить, ЧТО именно он забывает:
 * иначе однажды его позовут, ожидая совсем другого.
 *
 * 🔒 ВОЗВРАЩАЕТ ЧИСЛО СТЁРТОГО, А НЕ «ГОТОВО». Число доказывает, что стёрли
 * именно то, что было; «готово» одинаково выглядит и при удачной очистке, и при
 * очистке пустоты, и при очистке не того файла.
 */
export async function forget_journal({ lang } = {}) {
  const done = await clear()
  if (!done.ok) {
    return {
      error: done.error,
      ok: false,
      what_happened: say("journal-clear-failed", lang),
    }
  }
  return {
    cleared: done.cleared,
    ok: true,
    what_happened: done.cleared
      ? say("journal-cleared", lang, { n: done.cleared })
      : say("journal-was-empty", lang),
  }
}
