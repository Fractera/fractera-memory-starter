// 🔒 ЭТО НЕ «ЛОГИКА ВНУТРИ ПАМЯТИ», КОТОРУЮ ЗАПРЕЩАЕТ §4 ЗАПИСКИ. Запрет там про фильтрацию и
// сортировку ЧУЖИХ данных — про то, что должно жить отдельным микросервисом. Здесь память отвечает
// о СЕБЕ: где она стоит и как её зовут. Не знать этого о себе — не скромность, а дефект.
//
// 🛑 ОТВЕТ БЕРЁТСЯ ИЗ ИЗМЕРЕНИЯ, А НЕ ИЗ ТЕКСТА. Ни одна строка ниже не сочиняет фактов: всё
// приходит из `state()` и из договора. Сочинённый ответ о себе — самый убедительный род лжи.

import { contract } from "../contract.mjs"
import { state } from "./state.mjs"

/**
 * Похоже ли, что спрашивают о самой службе.
 *
 * 🔒 ГРУБО И НАМЕРЕННО: список слов, а не модель. Ход модели ради того, чтобы понять вопрос о
 * собственном порте, стоит дороже самого ответа — а закон 158-4 велит считать ходы, а не
 * миллисекунды.
 * 🛑 ПРОМАХ ЗДЕСЬ ДЁШЕВ И ОБРАТИМ: не узнали вопрос — память просто пойдёт обычной лестницей.
 * Поэтому список короткий; расширять его следует промахнувшимися фразами, а не воображением.
 */
const ASKS_SELF = [
  // 🛑 ГРАНИЦА СЛОВА ЗАДАНА ПРОСМОТРОМ, А НЕ ГРАНИЦЕЙ СЛОВА РЕГУЛЯРНОГО ВЫРАЖЕНИЯ: она в JavaScript
  // считает словом только ASCII, и перед кириллицей не срабатывает НИКОГДА. ✗ Оплачено здесь же,
  // стороже чисел: английские образцы ловились, русские — ни разу, и «Где ты сейчас» уходило
  // искать ответ в чужих словах.
  /(?<![а-яё])где (ты|мы)(?![а-яё])/i,
  /(?<![а-яё])кто ты(?![а-яё])/i,
  /(?<![а-яё])что ты такое(?![а-яё])/i,
  /(?<![а-яё])(на )?каком порт/i,
  /(?<![а-яё])какой порт/i,
  /(?<![а-яё])субдомен/i,
  /(?<![а-яё])какой домен/i,
  /защищ[а-яё]* ?(ли )?(соединени|поток|канал)/i,
  /(?<![а-яё])по ip(?![а-яё])/i,
  /(?<![а-яё])что ты умеешь(?![а-яё])/i,
  /(?<![а-яё])какие у тебя (глагол|метод|команд)/i,
  /where are you/i,
  /who are you/i,
  /which port/i,
  /your domain/i,
  /what can you do/i,
]

export function asksAboutSelf(text) {
  const q = String(text ?? "")
  return ASKS_SELF.some((re) => re.test(q))
}

/**
 * Ответ о себе: состояние плюс то, что память умеет делать.
 *
 * @param {{text?: string, lang?: string, seen?: {host?: string, proto?: string}}} input
 */
export function aboutSelf({ lang, seen } = {}) {
  const st = state(seen ?? {})
  const verbs = contract().methods.map((m) => m.name)
  const ru = lang !== "en"

  const lines = ru
    ? [
        st.what_happened,
        `договор ${contract().version}, глаголов ${verbs.length}: ${verbs.join(" · ")}`,
        st.planned.subdomain
          ? `по замыслу я живу на субдомене «${st.planned.subdomain}» и порту ${st.planned.port}`
          : `субдомена у меня нет: меня зовут по петле, порт ${st.planned.port}`,
        `вход: ${st.auth}`,
      ]
    : [
        st.what_happened,
        `contract ${contract().version}, verbs ${verbs.length}: ${verbs.join(" · ")}`,
        st.planned.subdomain
          ? `by design I live on subdomain «${st.planned.subdomain}», port ${st.planned.port}`
          : `no subdomain: I am reached over the loopback, port ${st.planned.port}`,
        `auth: ${st.auth}`,
      ]

  return {
    // 🔒 ЭТО ТВЁРДЫЙ ОТВЕТ: он измерен, а не выведен. Но расхождение с реестром делает его
    // зависящим от параметра — от того, каким адресом позвали.
    certainty: st.mismatch.length ? "depends" : "affirmative",
    ...(st.mismatch.length ? { depends_on: ["address"] } : {}),
    // 🔒 ПЕРВАЯ СТУПЕНЬ: ни базы, ни графа, ни вектора, ни хода модели. Вопрос о себе обязан быть
    // мгновенным — иначе человек, спросивший «где ты», ждёт девять секунд, как это и случилось.
    depth_used: 1,
    known: [{ claim: "stated", found_by: "self", value: lines.join("\n"), what: "о самой памяти" }],
    ok: true,
    state: st,
    used_model: false,
    what_happened: st.what_happened,
  }
}
