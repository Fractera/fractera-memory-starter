// была построена часом раньше АДРЕСОМ `GET /v1/state`, а человек спрашивает ГЛАГОЛОМ. `recall`
// пошёл искать ответ в том, что рассказывали люди, и честно не нашёл.
//
// 🔒 ЗАКОН, КОТОРЫЙ ЭТО НАРУШАЛО, У НАС УЖЕ БЫЛ: способность, написанная и не подключённая к тому
