//
// 🎯 §4 ЗАПИСКИ ВЛАДЕЛЬЦА, ПЕРВЫЙ ПУНКТ: «определить, к какому формату стоит отнести запрос
// пользователя: запрос на добавление данных · запрос на извлечение данных · обратная связь по
// предыдущему ответу».
//
// ✗ ЧЕМ ОПЛАЧЕНО: я построил на стенде кнопку «неразобранный запрос» как ПОЛЕ ДЛЯ JSON — и владелец
// честно получил `400 bad-json`. Его слова: «я же не машина, чтобы писать JSON, я пишу тебе обычные
// слова». Он прав: «неразобранный» — это про то, что запрос ЕЩЁ НЕ ОТНЕСЁН к глаголу, а не про то,
// что тело не разобрано парсером.
// 🔒 ЗАКОН ШИРЕ СЛУЧАЯ: СЛОВО ИЗ ЗАДАНИЯ ЧИТАЕТСЯ ГЛАЗАМИ ЧЕЛОВЕКА, А НЕ ГЛАЗАМИ КОДА. «Сырой»,
// «неразобранный», «как есть» у человека значат «я говорю по-человечески», а у программиста —
// «данные без обработки». Совпадение слов скрыло разные предметы.
//
// 🔒 БЕЗ ХОДА МОДЕЛИ, ПОКА ХВАТАЕТ ПРИЗНАКОВ. Ход модели ради того, чтобы отличить вопрос от
// рассказа, стоил бы дороже самого ответа (закон 158-4: считай ходы, а не миллисекунды).
// 🛑 И ВЫБОР ВСЕГДА НАЗЫВАЕТСЯ ВСЛУХ: «я понял это как…». Молча выбранный глагол — это уверенное
// умолчание, которое человек замечает только по неверному ответу.

/** Имя ответа в тексте: «ответ ans_90 слишком длинный». */
const ANSWER_ID = /\bans_(\d+)\b/i

/** Слова, которыми человек комментирует ПРЕДЫДУЩИЙ ответ, а не рассказывает новое. */
const FEEDBACK_WORDS = [
  "твой ответ", "этот ответ", "предыдущий ответ", "ты ответил", "ты написал",
  "мне не понравил", "не то ответил", "плохой ответ", "хороший ответ", "слишком длинн",
  "короче бы", "your answer", "that answer", "you replied",
]

/** Начала вопроса. Список грубый намеренно: промах дёшев и исправляется одним словом человека. */
const ASK_STARTS = [
  "что", "кто", "где", "когда", "какой", "какая", "какие", "сколько", "почему", "зачем", "чей",
  "напомни", "расскажи", "покажи", "найди", "знаешь", "помнишь", "перечисли",
  "what", "who", "where", "when", "which", "how", "why", "remind", "show", "find", "list",
]

/** Слова, которыми человек просит ЗАПОМНИТЬ. Сильнее вопросительных: «запомни, что я спрашивал…». */
const SAY_STARTS = ["запомни", "запиши", "сохрани", "заметь", "имей в виду", "remember", "note that", "save"]

const firstWord = (q) => q.trim().toLowerCase().split(/[^a-zа-яё]+/).filter(Boolean)[0] ?? ""

/**
 * Какой это из трёх глаголов — и почему именно этот.
 *
 * @param {string} text — слова человека как есть
 * @returns {{verb: "remember"|"recall"|"feedback", why: string, about?: string}}
 */
export function whichVerb(text) {
  const q = String(text ?? "").trim()
  const low = q.toLowerCase()

  // 1. Назван ответ — это комментарий к нему, и спорить не о чем.
  const named = ANSWER_ID.exec(q)
  if (named) return { about: `ans_${named[1]}`, verb: "feedback", why: `названо имя ответа ${named[0]}` }

  // 2. Речь о нашем ответе словами — тоже комментарий.
  const fw = FEEDBACK_WORDS.find((w) => low.includes(w))
  if (fw) return { verb: "feedback", why: `речь о предыдущем ответе: «${fw}»` }

  // 3. Просьба запомнить сильнее вопросительного слова: «запомни, что я спрашивал вчера» — это запись.
  const sw = SAY_STARTS.find((w) => low.startsWith(w))
  if (sw) return { verb: "remember", why: `просьба запомнить: «${sw}»` }

  // 4. Вопрос — по вопросительному знаку или по первому слову.
  if (q.endsWith("?")) return { verb: "recall", why: "заканчивается вопросительным знаком" }
  const w1 = firstWord(low)
  if (ASK_STARTS.includes(w1)) return { verb: "recall", why: `начинается с вопросительного слова «${w1}»` }

  // 5. Иначе — человек рассказывает. 🔒 УМОЛЧАНИЕ ВЫБРАНО НЕ ПО ЧАСТОТЕ, А ПО ЦЕНЕ ОШИБКИ: принять
  // рассказ за вопрос значит НЕ ЗАПОМНИТЬ сказанное — потеря; принять вопрос за рассказ значит
  // лишнюю запись, которую видно и легко поправить.
  return { verb: "remember", why: "ни вопроса, ни отзыва — человек рассказывает" }
}

/** Словами для человека: как мы это поняли. */
export function whichVerbWords({ verb, why }, lang) {
  const ru = lang !== "en"
  const name = ru
    ? { feedback: "отзыв о предыдущем ответе", recall: "вопрос", remember: "то, что нужно запомнить" }[verb]
    : { feedback: "a comment on a previous answer", recall: "a question", remember: "something to remember" }[verb]
  return ru
    ? `Я понял это как ${name} (${why}). Если не так — скажите, и я переделаю.`
    : `I read this as ${name} (${why}). If that is wrong, say so and I will redo it.`
}
