// СТАНДАРТ ИМЕНИ — ПУТЬ ОТ ЧЕЛОВЕКА ВНИЗ.
//
// 🔒 РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-09: имя таблицы обязано **само** объяснять, что в
// ней и чья она, — чтобы модель, запросив только список имён, поняла, что есть,
// и не ходила за описанием. Дословно: «пусть будет даже больше восьми слов, хоть
// 20, зато модель запросит через API названия таблиц и просто уже из названия
// поймёт, что нужно».
//
//   person_who_owns_this_project
//   person_who_owns_this_project__people_in_his_circle
//   person_who_owns_this_project__people_in_his_circle__their_vehicles
//
// `__` разделяет УРОВНИ, `_` — слова внутри уровня. Разбирается механически и
// читается глазами.
//
// 🔒 ПОДЧЁРКИВАНИЕ, А НЕ ДЕФИС — решение владельца после довода: дефис в имени
// таблицы SQL требует кавычек в КАЖДОМ запросе, и одна забытая ломает молча.
//
// 🔒 ТОЛЬКО АНГЛИЙСКИЕ СЛОВА (его же решение). И это не вкус: имя уезжает в
// `CREATE TABLE`, а белый список кириллицу не пропускает — оплачено шагом 81,
// где ключ признака, попавший в SQL без проверки, переставал быть именем.
//
// 🛑 ИМЯ ОТРАЖАЕТ ПРОИСХОЖДЕНИЕ, А НЕ ТЕКУЩЕЕ МЕСТО. Если сущность когда-нибудь
// переедет к другому родителю, имя не переписывается: переписанное начнёт лгать
// о прошлом, а на именах висят пути.

/** Корень. Имя вечное — от него идут все остальные. */
export const ROOT = "person_who_owns_this_project"

/** История правок корня. Дочерняя по стандарту — потому что она и есть дочерняя. */
export const ROOT_HISTORY = `${ROOT}__what_he_told_us_before`

/**
 * 🔒 БЕЛЫЙ СПИСОК — ЕДИНСТВЕННАЯ ГРАНИЦА БЕЗОПАСНОСТИ ИМЁН.
 * Имя рождается из свободной речи человека через модель. Попав в `CREATE TABLE`
 * без проверки, оно перестаёт быть именем и становится SQL.
 * ✗ Оплачено шагом 81: `field.money; DROP TABLE tgdesk_messages` обязано давать
 * пустое имя, а не таблицу.
 */
const SAFE = /^[a-z][a-z0-9_]{2,199}$/

/** Годно ли имя для SQL. Единственная проверка, других нет и не должно быть. */
export function isSafeName(name) {
  if (typeof name !== "string") return false
  if (!SAFE.test(name)) return false
  // Три подчёркивания подряд означали бы пустой уровень — имя без смысла.
  if (name.includes("___")) return false
  return true
}

/**
 * Привести предложенное моделью имя к стандарту.
 * Возвращает пустую строку, если привести не удалось, — и это ЗАКОННЫЙ исход,
 * а не ошибка: лучше отказать, чем завести таблицу со странным именем навсегда.
 */
export function normalizeName(raw) {
  if (typeof raw !== "string") return ""
  const cleaned = raw
    .trim()
    .toLowerCase()
    .replace(/[\s-]+/g, "_")
    .replace(/[^a-z0-9_]/g, "")
    .replace(/_{4,}/g, "__")
    .replace(/^_+|_+$/g, "")
  return isSafeName(cleaned) ? cleaned : ""
}

/** Имя ребёнка: путь родителя плюс свой уровень. */
export function childOf(parent, segment) {
  const seg = normalizeName(segment)
  if (!seg || !isSafeName(parent)) return ""
  const full = `${parent}__${seg}`
  return isSafeName(full) ? full : ""
}

/** Уровни имени — для человека и для экрана: кто чей родитель, видно из имени. */
export function levelsOf(name) {
  return isSafeName(name) ? name.split("__") : []
}

/** Родитель по имени, или пустая строка у корня. */
export function parentOf(name) {
  const l = levelsOf(name)
  return l.length > 1 ? l.slice(0, -1).join("__") : ""
}
