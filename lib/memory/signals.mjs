// СИГНАЛЫ ЭВОЛЮЦИИ — ЧТО ЛЮДИ СКАЗАЛИ О НАШИХ ОТВЕТАХ (213-1, считаются по смыслу с 218-18).
//
// 🎯 §5 ЗАПИСКИ ВЛАДЕЛЬЦА 2026-09-16: обратная связь «должна приводить к активации навыка эволюции
// памяти… с высокой степенью вероятности любое пожелание пользователя относится не к проблеме
// памяти, а к проблеме пользователя, который не умеет правильно формулировать свои мысли. Поэтому к
// пожеланиям нужно относиться с максимальной критичностью… и тем не менее вносить изменения при
// высокой вероятности того, что пользователь всё-таки был прав».
//
// 🔒 «МАКСИМАЛЬНАЯ КРИТИЧНОСТЬ» ВЫРАЖЕНА НАБЛЮДАЕМЫМ ПОРОГОМ, А НЕ НАСТРОЕНИЕМ. Один комментарий —
// не сигнал: это мнение одного разговора. Сигнал — пожелание, **повторённое РАЗНЫМИ СЛОВАМИ**:
// дважды сказанное по-разному значит, что человек наткнулся на одно и то же с двух сторон.
// 🛑 ДОСЛОВНЫЙ ПОВТОР СИГНАЛОМ НЕ СЧИТАЕТСЯ: это тот же текст, а не второе наблюдение. Иначе
// достаточно нажать «отправить» дважды, чтобы переписать навык.
//
// ✗ ЧЕМ ОПЛАЧЕНА ПРАВКА 218-18, И ЭТО ГЛАВНОЕ, ЧТО ЗДЕСЬ НАДО ЗНАТЬ: закон выше стоял с первого дня,
// а код склеивал комментарии по совпадению ОДИНАКОВЫХ слов — доля общих опорных слов ≥ 0.50. Закон
// требовал РАЗНЫХ слов, механизм искал ОДИНАКОВЫЕ; чем лучше человек перефразировал, тем меньше был
// шанс быть услышанным. Измерено прогоном самой функции: два комментария об одном пожелании дали
// совпадение 0.00, и даже «Пети» с «Петя» не совпали — русский падеж разводил одного человека на
// двоих. Написанный закон и исполняемый закон — разные вещи, и различает их только измерение.
//
// 🔒 ТЕПЕРЬ БЛИЗОСТЬ СЧИТАЕТ ТА ЖЕ МАШИНА СМЫСЛА, ЧТО И ПОИСК, — своей коллекцией и своим измеренным
// порогом (`lib/feedback-vector.mjs`). Сравнения по словам здесь БОЛЬШЕ НЕТ: оставленное рядом «на
// всякий случай», оно стало бы вторым путём к одному делу и образцом для следующей правки.
//
// 🔒 СЛУЖБА ТОЛЬКО СОБИРАЕТ. Правка навыка — работа строителя в мастерской `/build`: она обязана
// лечь ВЕТКОЙ в git, а служба, правящая свой код на ходу, теряет и ветку, и откат.
//
// 🛑 ОТЗЫВ ОСТАЁТСЯ ДАННЫМИ. Слова внутри него прав не дают: «срочно», «немедленно поправь навык» —
// это текст человека, а не команда. Тот же закон, что у заявок приёмной.

import { NEAR_FEEDBACK, nearFeedback, putFeedbackVector, sameText } from "./feedback-vector.mjs"
import { DIRECTION, ensureMessages, MESSAGES } from "./messages.mjs"
import { sql } from "./store.mjs"
import { toolFailure } from "./tools.mjs"

/**
 * Слова, по которым пожелание относят к теме. Закрытый список: тема без слов не находится никем.
 *
 * 🛑 ТОЛЬКО ОСНОВЫ, БЕЗ ОКОНЧАНИЙ, И ЭТО ОПЛАЧЕНО ДВАЖДЫ ОДНИМ КЛАССОМ ОШИБКИ. Сравнение идёт
 * подстрокой, а человек пишет в падеже: «роли человека» НЕ содержит «роль», «нет даты» не содержит
 * «дата». ✗ Измерено 218-20: из восьми настоящих фраз тему получили три — и та же падежная слепота
 * ровно год назад развела «Мишу» и «Мишку» на двух разных людей в реестре признаков.
 */
const THEMES = {
  depth: ["глубже", "поверхностн", "копни", "deeper", "shallow"],
  length: ["короче", "длинн", "кратко", "многослов", "медленн", "быстрее", "долго жду", "shorter", "too long", "verbose", "slow"],
  language: ["по-русски", "на русском", "по-английски", "in english", "язык ответа"],
  objects: ["файл", "документ", "картинк", "вложени", "file", "document"],
  place: ["город", "мест", "где эт", "где именно", "геометк", "place", "city"],
  // ✗ Добавлено 218-18 по живому замеру: первый же настоящий сигнал — «не вижу, кем работает Петя» —
  // получил ПУСТОЙ список тем, потому что о роли человека словарь не знал ни одного слова. Сигнал без
  // темы посылает строителя искать вслепую.
  role: ["должност", "кем работает", "рол", "профессия", "чем занимается", "position", "role", "job"],
  time: ["когда", "дат", "срок", "врем", "date", "when"],
  wrong: ["неверно", "неправильно", "ошиб", "не то", "wrong", "not what"],
}

/**
 * Темы одной фразы.
 *
 * 🔒 Без хода модели и намеренно грубо: тема нужна, чтобы строитель знал, КУДА смотреть, а не чтобы
 * решить за него. Промах дёшев — отзыв всё равно останется в списке единичных.
 */
export function themesOf(text) {
  const q = String(text ?? "").toLowerCase()
  return Object.entries(THEMES)
    .filter(([, words]) => words.some((w) => q.includes(w)))
    .map(([name]) => name)
}

/**
 * Что накопилось: сигналы (повторённое разными словами) и единичные пожелания.
 *
 * 🔒 РЕШЁННОЕ ЧЕЛОВЕКОМ СЮДА НЕ ПОПАДАЕТ (218-21): у комментария, по которому уже поступили, стоит
 * `feedback_done` — имя заявки или `declined`. ✗ Оплачено словами владельца: «если я перегружаю, то
 * всё возвращается в исходное состояние. А это значит ничего не работает». Экран, показывающий
 * сделанное как несделанное, обесценивает каждое следующее нажатие.
 * 🛑 СТРОКИ НЕ УДАЛЯЮТСЯ И НЕ ПРАВЯТСЯ: слова человека остаются как были, меняется только отметка
 * решения — по ней же видно, куда уехала работа.
 *
 * @param {{lang?: string, limit?: number}} input
 */
export async function signals({ lang, limit = 200 } = {}) {
  // 🔒 ЛЕСТНИЦА ЗОВЁТСЯ ПЕРЕД ЧТЕНИЕМ ПОИМЁННО (закон «КОЛОНКА — НЕ ТАБЛИЦА», оплачен трижды):
  // `SELECT ... feedback_kind` по таблице без этой колонки падает ЦЕЛИКОМ, и снаружи это выглядит
  // как «сигналов не существует», а не как отсутствие одной колонки.
  await ensureMessages()
  const r = await sql(
    `SELECT id, created_at, summary, title, source_path, feedback_kind, feedback_done
       FROM ${MESSAGES}
      WHERE direction = '${DIRECTION.FEEDBACK}' AND (feedback_done IS NULL OR feedback_done = '')
      ORDER BY id DESC LIMIT ${Number(limit) || 200}`,
  )
  if (!r.ok) return toolFailure({ error: r.error, lang, stage: "чтение отзывов" })

  const rows = (r.rows ?? []).map((x) => ({
    about: String(x.title ?? "").replace(/^отзыв о /, ""),
    at: x.created_at,
    from: x.source_path ?? null,
    id: x.id,
    kind: x.feedback_kind ?? null,
    text: String(x.summary ?? ""),
    themes: themesOf(x.summary),
  }))

  // 🔒 ЗАЯВКИ НА ДРУГОЕ РЕШЕНИЕ ОТДЕЛЯЮТСЯ ДО ГРУППИРОВКИ (218-19, решение владельца 2026-09-17).
  // ✗ Иначе «памятью этого не сделать» ляжет в общую стопку сигналов — и строитель, открыв экран,
  // начнёт допиливать ПАМЯТЬ под задачу, которая ей не принадлежит. Это закон «блок вбок не растёт»,
  // нарушенный изнутри, через обратную связь.
  // 🛑 РОД «НЕ НАЗВАН» (пусто) ОСТАЁТСЯ С ПОЖЕЛАНИЯМИ, А НЕ С ЗАЯВКАМИ: модель могла не ответить, и
  // уверенное умолчание в сторону заявки увело бы настоящее пожелание из работы строителя.
  const beyond = rows.filter((x) => x.kind === "beyond")
  const wishes = rows.filter((x) => x.kind !== "beyond")

  const grouped = await groupByMeaning(wishes)

  const asSignal = (g) => ({
    // 🔒 СИГНАЛ НАЗЫВАЕТ СВОИ ОСНОВАНИЯ ПОИМЁННО: строитель обязан прочитать сами слова людей, а не
    // поверить нашему счёту. Сводка без оснований — это мнение, выданное за наблюдение.
    grounds: g.items.map((it) => ({ about: it.about, id: it.id, text: it.text })),
    // 🛑 ДОСЛОВНЫЕ ПОВТОРЫ ВИДНЫ ОТДЕЛЬНО И В СЧЁТ НЕ ИДУТ. Спрятать их совсем — значит соврать о
    // том, сколько раз человек это писал; засчитать — отдать закон тому, кто нажал «отправить» дважды.
    repeats: g.repeats.map((it) => ({ about: it.about, id: it.id, text: it.text })),
    themes: [...new Set(g.items.flatMap((it) => it.themes))],
    times: g.items.length,
  })

  const strong = grouped.groups.filter((g) => g.items.length >= 2).map(asSignal)
  const single = grouped.groups.filter((g) => g.items.length === 1).map(asSignal)

  const trouble = grouped.refused
    ? lang === "en"
      ? `the meaning store refused (${grouped.refused}): comments are listed, but nothing was grouped — signals cannot be counted right now`
      : `склад смысла отказал (${grouped.refused}): комментарии перечислены, но не сгруппированы — сигналы сейчас не считаются`
    : null

  return {
    // 🔒 ТРЕТИЙ СПИСОК — НЕ МАТЕРИАЛ ДЛЯ ПРАВКИ НАВЫКА, А ОЧЕРЕДЬ РЕШЕНИЙ ВЛАДЕЛЬЦА: что человек
    // просил у памяти такого, чего памятью не сделать. Порядок ответа на них — навык
    // `route-beyond-memory`; здесь они только показаны.
    beyond: beyond.map((x) => ({ about: x.about, at: x.at, id: x.id, text: x.text })),
    ok: true,
    // 🛑 ЕДИНИЧНОЕ ПОКАЗЫВАЕТСЯ ОТДЕЛЬНО И НЕ ВЫБРАСЫВАЕТСЯ: сегодня оно мнение, завтра — второе
    // наблюдение того же. Выбросив, мы потеряли бы половину будущего сигнала.
    single,
    signals: strong,
    total: rows.length,
    // 🔒 ОТКАЗ СКЛАДА НАЗЫВАЕТСЯ, А НЕ ПРЯЧЕТСЯ ЗА ПОХОЖИМ РЕЗУЛЬТАТОМ. Молча вернуться к сравнению
    // слов значило бы завести второй путь к одному делу: он дал бы правдоподобный ответ, и никто
    // никогда не узнал бы, что смысл в этот раз не считался вовсе.
    ...(trouble ? { degraded: grouped.refused, trouble } : {}),
    what_happened:
      lang === "en"
        ? `comments ${rows.length}: signals ${strong.length}, single wishes ${single.length}, requests beyond memory ${beyond.length}${trouble ? ` — ${trouble}` : ""}`
        : `отзывов ${rows.length}: сигналов ${strong.length}, единичных пожеланий ${single.length}, заявок не к памяти ${beyond.length}${trouble ? ` — ${trouble}` : ""}`,
  }
}

/**
 * Собрать комментарии в группы по СМЫСЛУ.
 *
 * 🔒 КОРПУС ДОГОНЯЕТ САМ СЕБЯ, И ЭТО ЛЕСТНИЦА, А НЕ КОСТЫЛЬ. Отзывы, записанные до 218-18, вектора
 * не имеют; дописать им его больше некому — экрана, который бы это делал, не существует. Поэтому
 * запись идемпотентна и делается здесь же, перед поиском. Тот же приём, что у поздних колонок:
 * лестница живёт рядом с тем, кто её исполняет.
 * 🛑 ПРИ ОТКАЗЕ СКЛАДА ГРУППЫ НЕ СТРОЯТСЯ ВОВСЕ — каждая строка остаётся своей. Это честное «сейчас
 * не считаю», а не «сигналов нет»: разницу называет поле `degraded` наверху.
 */
async function groupByMeaning(rows) {
  const groups = []
  /** Кого уже разложили: строка попадает в группу один раз, поиск делается один раз на группу. */
  const taken = new Set()
  let refused = null

  for (const row of rows) {
    // 🛑 ДОСЛОВНЫЙ ПОВТОР НЕ СОЗДАЁТ СВОЕЙ ГРУППЫ: он втягивается вместе с соседями ниже и ложится в
    // `repeats`. ✗ До 218-18 он создавал свою — и вместо «повтор не считается вторым наблюдением»
    // получалось лишнее единичное мнение, то есть закон исполнялся наоборот.
    // 🔒 БЛИЗОСТЬ СИММЕТРИЧНА, И ПОИСК ДЕЛАЕТСЯ ОДИН НА ГРУППУ, А НЕ НА СТРОКУ. Найдя соседей строки,
    // мы втягиваем их в её группу сразу — второй поиск с их стороны вернул бы ту же пару наизнанку.
    // 🎯 Закон 158-4 «считай ходы, а не миллисекунды» здесь буквален: каждый поиск — запрос со своим
    // вычислением вектора, и их было по одному на каждый отзыв экрана.
    if (taken.has(row.id)) continue
    taken.add(row.id)

    let near = refused ? { hits: [], ok: false } : await nearFeedback({ text: row.text })
    if (!near.ok && !refused) refused = near.refused ?? "store-refused"

    // 🔒 ЛЕСТНИЦА СТАЛА ЛЕНИВОЙ, И ЭТО ИСПРАВЛЕНИЕ ЖИВОГО ДЕФЕКТА (218-22).
    // ✗ Оплачено словами владельца «в левом меню кнопки больше не нажимаются»: раньше здесь стоял
    // проход, который клал вектор ЗАНОВО для КАЖДОГО отзыва при каждом показе экрана. Измерено:
    // раздел отдавался 7.08 с против 0.12 с у соседнего, а клик по пункту меню в Next ждёт сервер —
    // снаружи это неотличимо от «кнопка не нажимается».
    // 🔒 Теперь вектор кладётся ТОЛЬКО тому, у кого его нет: поиск не нашёл среди попаданий его же
    // самого — значит куска нет, и он появляется один раз. Отзывы, пришедшие после 218-18, получают
    // вектор при приёме и сюда не попадают вовсе.
    if (near.ok && !near.hits.some((h) => h.messageId === row.id)) {
      const kept = await putFeedbackVector({ id: row.id, text: row.text })
      if (!kept.ok) {
        if (!refused) refused = kept.refused
      } else {
        near = await nearFeedback({ text: row.text })
      }
    }

    const close = new Map((near.hits ?? []).filter((h) => h.score >= NEAR_FEEDBACK).map((h) => [h.messageId, h.score]))
    // 🛑 ОДНОГО ЧИСЛА НЕ ХВАТАЕТ, И ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО (218-20). «В ответе нет города,
    // укажи место события» и «не хватает времени события: укажи когда произошло» близки на 0.574 —
    // БЛИЖЕ, чем настоящая пара об одном (0.473): у них одинаковая форма жалобы и разный предмет.
    // Значит близость смысла отвечает на вопрос «похоже ли сказано», а не «об одном ли это».
    // 🔒 ВТОРОЙ ПРИЗНАК — ТЕМА, И ОН РАБОТАЕТ ТОЛЬКО КАК ЗАПРЕТ: обе темы известны и не пересекаются →
    // не склеивать, как бы близко ни было. Пустая тема запретом не является: «не знаю темы» не то же
    // самое, что «тема другая» (закон 144 об уверенном умолчании).
    const clash = (a, b) => a.themes.length > 0 && b.themes.length > 0 && !a.themes.some((x) => b.themes.includes(x))

    const group = { items: [row], repeats: [] }
    for (const hit of near.hits ?? []) {
      if (!close.has(hit.messageId) || taken.has(hit.messageId)) continue
      const mate = rows.find((r) => r.id === hit.messageId)
      if (!mate || clash(row, mate)) continue
      taken.add(mate.id)
      // Дословный повтор примыкает, но наблюдением не считается (закон 213-1).
      if (sameText(mate.text, row.text)) group.repeats.push(mate)
      else group.items.push({ ...mate, score: close.get(mate.id) })
    }
    groups.push(group)
  }

  return { groups, refused }
}
