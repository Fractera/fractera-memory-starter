// обрезанные строки. Не прошедшее проверку отбрасывается ЦЕЛИКОМ: наполовину разобранное сохранят.
// 🛑 МОДЕЛЬ НЕ ОТВЕТИЛА — РОД НЕ НАЗВАН, И ЭТО НЕ «improve ПО УМОЛЧАНИЮ». Уверенное умолчание дороже
// отсутствующего значения (закон 144): молча записав заявку как пожелание, мы отправили бы строителя
// допиливать память под задачу, которая ей не принадлежит.

import { think } from "./think.mjs"

/** Закрытый список родов. Всё, чего здесь нет, — не род, а выдумка модели. */
export const KIND = { BEYOND: "beyond", IMPROVE: "improve" }

const SYSTEM = `Ты разбираешь ОДИН комментарий человека о работе сервиса памяти.
Сервис памяти умеет: запоминать сказанное, отвечать по накопленному, хранить файлы и ссылки,
связывать людей и события, искать по смыслу. Он НЕ умеет: аналитику рынка, бухгалтерию, рассылки,
управление задачами, авторизацию, торговлю — это другие продукты.

Верни СТРОГО JSON:
{
  "kind": "improve" | "beyond",
  "asked": "<чего человек хочет, одной фразой его словами>",
  "can_promise": true | false,
  "why_not": "<если can_promise=false: почему надёжно пообещать нельзя, одной фразой>",
  "could_do": "<что при этом можно было бы сделать, одной фразой; пусто, если нечего>"
}

"improve" — человек просит делать ТО ЖЕ САМОЕ иначе: полнее, короче, точнее, на другом языке,
с другими подробностями. Это пожелание к работе памяти.
"beyond" — человек говорит, что нужного он от памяти не получит в принципе: это задача другого
продукта, другого сервиса, отдельной разработки.
"can_promise" — ВНИМАНИЕ: вопрос НЕ о памяти. Он о том, можно ли надёжно решить эту задачу ОТДЕЛЬНЫМ
решением — готовым продуктом или новым микросервисом, если его построить.
true — задача понятная и ограниченная, у неё есть исполнитель и проверяемый результат (рассылки,
счета, расписание, аналитика по собранным данным).
false — задача расплывчата, требует данных, которых взять неоткуда, или результат нечем проверить
(предсказать спрос без истории продаж, «сделать красиво», «чтобы всё работало само»).
🛑 То, что ПАМЯТЬ этого не умеет, уже сказано родом "beyond" — не отвечай этим ещё раз здесь.
Никакого текста вне JSON.`

const trim = (v, n = 300) => (typeof v === "string" ? v.trim().slice(0, n) : "")

/**
 * Какого рода этот комментарий.
 *
 * @param {string} text — комментарий как есть
 * @returns {Promise<{ok: boolean, kind?: string, asked?: string, can_promise?: boolean, why_not?: string, could_do?: string, refusal?: string}>}
 */
export async function feedbackKind(text) {
  const body = String(text ?? "").trim()
  if (!body) return { ok: false, refusal: "empty-text" }

  const answer = await think(SYSTEM, body)
  if (!answer.ok) return { ok: false, refusal: answer.refusal ?? "model-refused" }

  const kind = answer.data?.kind
  // 🛑 РОД — ТОЛЬКО ИЗ ЗАКРЫТОГО СПИСКА. Модель вернёт «maybe» или «suggestion», и выглядеть это
  // будет убедительно; выдуманный род отправил бы комментарий не в ту стопку молча.
  if (kind !== KIND.IMPROVE && kind !== KIND.BEYOND) return { ok: false, refusal: "kind-outside-list" }

  return {
    asked: trim(answer.data?.asked) || body.slice(0, 300),
    // 🔒 «МОЖНО ПООБЕЩАТЬ» — ЭТО ВОПРОС О БУДУЩЕМ РЕШЕНИИ, А НЕ О ПАМЯТИ, и формулировка здесь была
    // исправлена измерением. ✗ Первая редакция промпта спрашивала «можно ли надёжно пообещать
    // результат», перечисляя среди причин отказа «требует данных, которых память не видит» — а у
    // заявки `beyond` это верно ПО ОПРЕДЕЛЕНИЮ. Прибор показал: четыре случая из четырёх ушли в
    // честный отказ, и ветка «предложить микросервис» оказалась НЕДОСТИЖИМОЙ — способность написана
    // и не вызывается никем, ровно тот класс, который мы ловим вопросом «кто её зовёт».
    // 🛑 Молчание модели читается как «обещать нельзя»: осторожность дешевле ложного обещания.
    can_promise: answer.data?.can_promise === true,
    could_do: trim(answer.data?.could_do),
    kind,
    ok: true,
    why_not: trim(answer.data?.why_not),
  }
}

/**
 * Честный отказ словами — три части, и ни одна не пропускается.
 *
 * 🎯 СЛОВА ВЛАДЕЛЬЦА 2026-09-17: «отказать пользователю это тоже распространённый вариант: К
 * сожалению сложно гарантировать сейчас надёжное решение в соответствии с вашими пожеланиями. Потому
 * что бла-бла-бла. Вот что можно было бы сделать: бла-бла-бла. Если хотите мы продолжим обсуждение
 * или просто давайте вернёмся к обычной работе».
 *
 * 🛑 ПРЕДЛОЖЕНИЕ СОЗДАТЬ МИКРОСЕРВИС НЕ СТАВИТСЯ НА КАЖДУЮ ЗАЯВКУ. Обещание, которого продукт не
 * держит, человек проверяет в свой худший день — поэтому там, где обещать нечего, стоит отказ с
 * названной причиной, названной альтернативой и выбором, отданным человеку.
 */
export function refusalWordsFor({ asked, could_do, lang, why_not }) {
  const ru = lang !== "en"
  // 🛑 Модель возвращает фразы то с точкой, то без: «…память не видит.» + наша точка = «не видит..».
  // Мелочь, по которой человек видит, что текст собран машиной небрежно.
  const noDot = (s) => String(s ?? "").replace(/\s*[.!?]+\s*$/, "")
  const reason = noDot(why_not) || (ru ? "у этой задачи нет ни готового решения, ни службы на этом сервере" : "there is neither a ready solution nor a service on this server for it")
  const instead = could_do
    ? ru
      ? `Вот что можно было бы сделать: ${noDot(could_do)}`
      : `Here is what could be done: ${noDot(could_do)}`
    : ru
      ? "Готового пути, который я могла бы честно предложить, у меня сейчас нет"
      : "I have no honest path to offer right now"
  return ru
    ? `К сожалению, надёжное решение по просьбе «${asked}» я сейчас гарантировать не могу. Потому что ${reason}. ` +
        `${instead}. Если хотите — продолжим обсуждение, или просто вернёмся к обычной работе.`
    : `Unfortunately I cannot guarantee a reliable solution for «${asked}» right now. Because ${reason}. ` +
        `${instead}. If you want, we can keep discussing it — or simply go back to normal work.`
}
