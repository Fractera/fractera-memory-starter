import { SERVICES } from "./services.mjs"
import { ME } from "./state.mjs"

/**
 * Просьбы, адресованные не памяти.
 *
 * @param {string} text — фраза человека как есть
 * @returns {Array<{service: string, manage: string|null, matched: string}>}
 */
export function elsewhere(text) {
  const q = String(text ?? "").toLowerCase()
  if (!q) return []
  const out = []
  for (const s of SERVICES) {
    // 🔒 О СЕБЕ ПАМЯТЬ НЕ ПЕРЕАДРЕСОВЫВАЕТ: на вопрос о себе она отвечает сама (`about-self.mjs`).
    if (s.id === ME) continue
    const hit = (s.topics ?? []).find((w) => q.includes(String(w).toLowerCase()))
    if (!hit) continue
    // 🔒 ЧЕЛОВЕКУ ПОКАЗЫВАЕТСЯ ЕГО СЛОВО, А НЕ НАШ КОРЕНЬ. «просьба про авторизац» читается как
    // опечатка машины; «про авторизацию» — как то, что он и сказал.
    const whole = new RegExp("[a-zа-яё]*" + hit + "[a-zа-яё]*", "i").exec(q)?.[0] ?? hit
    out.push({ channels: s.channels ?? null, manage: s.manage ?? null, matched: whole, service: s.id })
  }
  return out
}

/**
 * Подставить настоящий домен вместо образца в ссылке реестра.
 *
 * 🔒 РЕЕСТР ХРАНИТ ОБРАЗЕЦ, А НЕ АДРЕС ЭТОГО СЕРВЕРА: файл одинаков во всех службах и на всех
 * серверах, а домен у каждого свой. Настоящий домен известен только из ЗАПРОСА — оттуда и берётся.
 * 🛑 Домена не знаем — отдаём образец как есть: выдуманный адрес хуже честного шаблона.
 */
function withDomain(link, domain) {
  return domain ? String(link).replace("<domain>", domain) : link
}

/**
 * Словами для человека: что записано — и что не в наших полномочиях, с адресом.
 *
 * 🎯 СЛУЧАЙ ВЛАДЕЛЬЦА 2026-09-18: «если существует Telegram чат то ссылку надо будет кидать не на
 * сайт а на Telegram чат чтобы внутри телеграмма перейти с одного чата на другой».
 * 🔒 ОТВЕЧАЕМ В ТОМ КАНАЛЕ, КОТОРЫМ ПРИШЛА ПРОСЬБА. Человек, пишущий боту с телефона, не должен
 * выходить в браузер, чтобы попасть к соседнему боту: переход внутри мессенджера — это один тап,
 * а ссылка на сайт — смена приложения, вход и потерянная мысль.
 * 🛑 КАНАЛ НЕ НАЗВАН ИЛИ У СЛУЖБЫ ЕГО НЕТ — УХОДИТ ВЕБ-АДРЕС, КАК И РАНЬШЕ. Пустая ссылка была бы
 * хуже прежнего поведения: отказ без адреса есть тупик.
 *
 * @param {string|null} channel — род канала, которым пришла просьба (`"telegram"`), либо null
 */
export function elsewhereWords(list, lang, domain, channel = null) {
  if (!list.length) return ""
  const ru = lang !== "en"
  const linkOf = (x) => {
    const inChannel = channel ? x.channels?.[channel]?.url : null
    if (inChannel) return { url: inChannel, where: channel }
    return { url: x.manage ? withDomain(x.manage, domain) : null, where: "web" }
  }
  return list
    .map((x) => {
      const link = linkOf(x)
      // 218-13: называется ПРОСЬБА словами человека, когда её выделил разбор, а не слово, по которому нашли службу
      const what = x.request ?? x.matched
      if (ru) {
        const head = `просьба «${what}» — не мои полномочия: этим управляет служба «${x.service}»`
        if (!link.url) return head + ", своей страницы настройки у неё нет"
        return head + (link.where === "web" ? `, настроить можно здесь: ${link.url}` : `, перейдите к ней: ${link.url}`)
      }
      const head = `the request «${what}» is not mine to do: it belongs to «${x.service}»`
      if (!link.url) return head + ", which has no settings page of its own"
      return head + (link.where === "web" ? `, configured here: ${link.url}` : `, talk to it here: ${link.url}`)
    })
    .join("\n")
}
