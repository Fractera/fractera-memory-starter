// НАСКОЛЬКО ОТВЕТ ТВЁРДЫЙ — ОБЯЗАТЕЛЬНЫЙ АТРИБУТ ОТВЕТА (207-3).
//
// 🎯 СЛОВО ВЛАДЕЛЬЦА 2026-09-16: «Формат ответа модели должен включать в себя
// обязательный атрибут является ли ответ утвердительным, предположительным или
// зависимым от параметра что нужно раскрыть в ответе».
//
// 🔒 ТРИ ЗНАЧЕНИЯ, И ТРЕТЬЕ — САМОЕ ПОЛЕЗНОЕ. `affirmative` — сказанное лежит
// прямо; `presumed` — ответ собран моделью или по смыслу, а не точным
// совпадением; `depends` — известное расходится по обстоятельствам, и без
// названного параметра ответа просто не существует. Третье превращает тупик
// «не знаю» в вопрос «назовите город» — а это разные разговоры.
//
// 🔒 ПУСТО ЗНАЧИТ «СКАЗАТЬ НЕЧЕГО», А НЕ «УВЕРЕННО НЕТ» (закон 144): уверенное
// умолчание останавливает поиск, отсутствующее значение — нет.
//
// 🛑 СЧИТАЕТСЯ ПО ДАННЫМ, А НЕ ПО ВПЕЧАТЛЕНИЮ МОДЕЛИ. Если у найденного больше
// одного различного места или времени, ответ и правда зависит от того, о каком
// из них спрашивают. Модель тут не нужна, и звать её было бы платой за то, что
// видно из самих строк.
//
// 🔒 ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ФУНКЦИЯ ВНУТРИ ГЛАГОЛА: правило, спрятанное внутри,
// нельзя позвать прибором, а непроверяемое правило через месяц работает не так,
// как написано.

/**
 * @param {{known?: Array<{where?: string|null, at_scope?: string|null}>, used_model?: boolean, certainty?: string}} body
 * @returns {{certainty?: string, depends_on?: string[]}}
 */
export function certaintyOf(body = {}, qScope = null) {
  // Уже названо вызывающим — не переспрашиваем: он знает о своём ответе больше.
  if (body.certainty) return { certainty: body.certainty }

  // 🔒 ПОДТЯНУТОЕ ПО СВЯЗИ НЕ РЕШАЕТ ТВЁРДОСТЬ (218-10). ✗ Живой замер: связанная запись о другой дате
  // сделала ответ «зависящим от параметра» — хотя на сам вопрос нашлось одно и то же. Твёрдость говорит о
  // найденном, а не о том, что рядом с ним.
  const known = (Array.isArray(body.known) ? body.known : []).filter((k) => k?.found_by !== "link")
  if (known.length === 0) return {}

  // 🔒 ПОЛЯ ЧИТАЮТСЯ ОБОИХ ИМЁН (218-7). Находки из моста несут `place` и `at`; прежние — `where` и
  // `at_scope`. ✗ Правило искало только старые имена, и «зависящий от параметра» не срабатывал
  // НИКОГДА: место и время у находок появились, а твёрдость их не видела.
  const places = new Set(known.map((k) => k?.place ?? k?.where).filter(Boolean))
  const times = new Set(known.map((k) => k?.at ?? k?.at_scope).filter(Boolean))
  // 🔒 ПАРАМЕТР, УЖЕ НАЗВАННЫЙ В ВОПРОСЕ, ОТ ЗАВИСИМОСТИ СНЯТ (218-8). ✗ Живой замер: на «с кем Катя
  // встречается в Лондоне» память ответила «назовите, о каком месте вы спрашиваете» — место было
  // названо. Просить уже сказанное значит показать, что вопрос не прочитан.
  // Снимается, только если среди находок есть совпавшая: назвали Лондон, а записей о Лондоне нет —
  // зависимость остаётся, потому что ответ собран про другие места.
  const matched = (k) => k?.scope_fit === "match"
  const placeGiven = Boolean(qScope?.place) && known.some(matched)
  const timeGiven = Boolean(qScope?.at) && known.some(matched)
  const on = [places.size > 1 && !placeGiven ? "place" : null, times.size > 1 && !timeGiven ? "time" : null].filter(Boolean)
  if (on.length) return { certainty: "depends", depends_on: on }

  // 🔒 ТВЁРДОСТЬ ОПРЕДЕЛЯЕТСЯ ТЕМ, ЧЕМ НАЙДЕНО, А НЕ ТЕМ, ЗВАЛАСЬ ЛИ МОДЕЛЬ (218-2).
  //
  // ✗ ОПЛАЧЕНО ЖИВЫМ БЛОКОМ ВЛАДЕЛЬЦА 2026-09-16: ДЕВЯТЬ ОТВЕТОВ ИЗ ДЕВЯТИ пришли
  // «утвердительными» — включая ответ на вопрос о том, чего память не знала вовсе. Прежнее правило
  // звучало «модель не звалась — значит утвердительный», и оно неверно в самом основании: подбор по
  // смыслу и обход связей моделью не пользуются, но фактом от этого не становятся.
  //
  // 🔒 УТВЕРДИТЕЛЬНЫМ БЫВАЕТ ТОЛЬКО ТО, ЧТО ЛЕЖИТ ПРЯМО: ответ о самой службе (`self`) и факт,
  // сказанный человеком (`claim === "said"`). Вектор и граф — `presumed` по устройству: первый
  // сравнивает смысл, второй идёт по связям, и оба возвращают похожее, а не названное.
  // 🔒 САМОЕ СЛАБОЕ ЗВЕНО РЕШАЕТ ЗА ВЕСЬ ОТВЕТ: смесь точного и похожего — это похожий ответ.
  const SOFT = new Set(["vector", "graph", "graph2", "deep-memory", "world"])
  const soft = known.some((k) => SOFT.has(String(k?.found_by ?? "")) || k?.claim === "guess")
  return { certainty: soft || body.used_model ? "presumed" : "affirmative" }
}
