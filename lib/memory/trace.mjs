// 🎯 СЛОВО ВЛАДЕЛЬЦА 2026-09-16: «это не ответ, это цепочка мыслей… у неё должно быть время у всех
// элементов, а внизу я должен видеть настоящий ответ системы человеческим языком».
//
// 🔒 ОТСЮДА ДВЕ ЧАСТИ ОТВЕТА, И ОНИ НЕ ПУТАЮТСЯ. Машинная часть — это ход мыслей: что память делала,
// в каком порядке и КОГДА. Человеческая часть (`text`) — ответ словами, и он внизу. Раньше ход
// мыслей был строками без времени и отдавался только по просьбе, а человек читал «В память
// сохранено» и не мог понять, что вообще произошло.
//
// 🔒 ВРЕМЯ У ШАГА ДВОЙНОЕ, И ОБА ЗНАЧЕНИЯ НУЖНЫ: `at` — когда это случилось (по часам, его можно
// сверить с журналом и с чужой службой), `ms` — сколько прошло от начала запроса (по нему видно,
// какой шаг дорогой). Одно без другого не отвечает ни на «когда», ни на «почему долго».

/**
 * Завести ход мыслей одного запроса.
 *
 * @param {number} [startedAt] — начало запроса; по умолчанию сейчас.
 * @returns {{items: Array<{at: string, ms: number, note: string}>, step: (note: string) => void}}
 */
export function makeTrace(startedAt = Date.now()) {
  const items = []
  return {
    items,
    step(note) {
      const now = Date.now()
      items.push({ at: new Date(now).toISOString(), ms: now - startedAt, note: String(note ?? "") })
    },
  }
}
