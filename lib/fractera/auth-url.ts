// 🪦 СКОПИРОВАН СО СЛУЖБЫ ЧАТА (179-1, 2026-09-10) С ОДНОЙ ОБЯЗАТЕЛЬНОЙ ПРАВКОЙ:
// там адрес выводился ТОЛЬКО для хоста, начинающегося с `chat.`. Дословная
// копия дала бы памяти пустую строку — и страница приветствия сказала бы
// «адрес службы входа пока не настроен» при живом входе. Здесь приставка
// заменяется у ЛЮБОГО поддомена: `memory.<домен>` → `auth.<домен>`.
//
// ✗ ОПЛАЧЕНО ВЛАДЕЛЬЦЕМ ЖИВЬЁМ (у чата): кнопка «войти» на странице приветствия
// вела на `http://<ip сервера>:3001/login` — голый IP по НЕЗАЩИЩЁННОМУ http, где
// авторизации нет вовсе. Дословно: «мы уже переехали на защищённый маршрут, а
// ссылка отправляет нас на незащищённый».
//
// 🛑 ПРИЧИНА НЕ В ОПЕЧАТКЕ, А В ЗАПЕКАНИИ. `NEXT_PUBLIC_AUTH_URL` попадает в
// сборку и застывает: значение записано при рождении сервера, когда домена ещё
// не было. Подключив домен, человек обязан был бы вспомнить про пересборку —
// а он не обязан этого знать. Сервер, где домен появился позже, получал бы
// сломанный вход МОЛЧА.
//
// 🔒 ДВА МЕСТА СЧИТАЛИ ЭТОТ АДРЕС ПО ОТДЕЛЬНОСТИ — страница приветствия (вход) и
// раскладка (выход). Две сборки одного адреса расходятся на первой правке, и
// расходятся так, что одна половина работает: заметить это можно только нажав
// обе кнопки.

/**
 * Хост без первой метки: `memory.aifa.dev` → `aifa.dev`.
 *
 * 🔒 ПРИСТАВКА ЗАМЕНЯЕТСЯ, А НЕ УГАДЫВАЕТСЯ: службы — соседи по одному списку
 * `SUBDOMAINS` панели, откуда берутся и блоки nginx, и имена в сертификате.
 * 🛑 Хост без точки или из двух меток — это не поддомен службы, и ответ пустой:
 * сосчитать соседа тут не из чего, и угадывать его нельзя.
 */
function apexOf(host: string): string {
  if (!host || /:\d+$/.test(host)) return "";
  const parts = host.split(".");
  return parts.length > 2 ? parts.slice(1).join(".") : "";
}

/**
 * Куда браузер идёт входить и выходить.
 *
 * 🔒 ВЫВОДИТСЯ ИЗ ХОСТА, ПО КОТОРОМУ ОТКРЫТА САМА СЛУЖБА.
 * 🔒 ПЕРЕМЕННАЯ ОСТАЁТСЯ ЗАПАСНЫМ ПУТЁМ — для машины без домена (режим по IP) и
 * для разработки.
 */
export function publicAuthUrl(host: string, proto: string): string {
  const apex = apexOf(host);
  const fromHost = apex ? `${proto}://auth.${apex}` : "";
  return (
    fromHost ||
    process.env.NEXT_PUBLIC_AUTH_URL ||
    process.env.AUTH_SERVICE_URL ||
    ""
  );
}

// ── СОСЕДНИЕ СЛУЖБЫ: САЙТ И ПАНЕЛЬ ──────────────────────────────────────────
//
// 🔒 ТОТ ЖЕ ВЫВОД, ЧТО У ВХОДА, И ЖИВЁТ ОН ЗДЕСЬ ЖЕ — два места, считающие один
// адрес, расходятся так, что одна половина работает.
//
// 🔒 РЕЖИМ ПО IP — ЗАПАСНОЙ ПУТЬ: `<адрес>:<свой порт>` → `<адрес>:<порт соседа>`.
// У чата здесь стоял образец только для `:3600`; у памяти порт свой, поэтому
// образец принимает любой порт — порты соседей есть факт развёртывания.
//
// 🛑 ПУСТАЯ СТРОКА — ЗАКОННЫЙ ОТВЕТ: ссылка в никуда хуже её отсутствия.

function siblingByHost(host: string, proto: string, prefix: string, port: string): string {
  const apex = apexOf(host);
  if (apex) {
    return `${proto}://${prefix}${apex}`;
  }
  const m = host.match(/^(.+):(\d+)$/);
  return m ? `${proto}://${m[1]}:${port}` : "";
}

/** Публичный адрес САЙТА (гостевое приложение, `:3000`). */
export function publicSiteUrl(host: string, proto: string): string {
  return siblingByHost(host, proto, "", "3000") || process.env.NEXT_PUBLIC_APP_URL || "";
}

/** Публичный адрес ПАНЕЛИ управления (`admin.`, `:3002`). */
export function publicAdminUrl(host: string, proto: string): string {
  return siblingByHost(host, proto, "admin.", "3002") || process.env.NEXT_PUBLIC_ADMIN_URL || "";
}

/**
 * Публичный адрес САМОЙ ПАМЯТИ — тот, по которому человек сейчас её открыл (185-2).
 *
 * 🔒 БЕРЁТСЯ ИЗ ЗАПРОСА, А НЕ ИЗ ПЕРЕМЕННОЙ И НЕ ИЗ КОНСТАНТЫ. Требование
 * владельца 2026-09-11, дословно: «Хочу быть уверен в том что домен здесь не
 * является хардкор а подставляется строго в соответствии с реальным доменном».
 * Адрес в примерах документации и в инструкции Postman обязан быть тем, по
 * которому читатель пришёл: на другом сервере страница сама скажет другое.
 *
 * 🛑 ПЕРЕМЕННАЯ ОКРУЖЕНИЯ ЗДЕСЬ ХУЖЕ ЗАПРОСА, И ЭТО ОПЛАЧЕНО У СОСЕДА ВЫШЕ:
 * записанная при рождении сервера, она застывает, а подключённый позже домен
 * ломает её МОЛЧА. Запрос знает правду всегда.
 *
 * 🔒 ЗАПАСНОЙ ПУТЬ — ПЕТЛЯ, И ЭТО ЧЕСТНО: пока службу открывают не по домену,
 * снаружи её и правда нет. Обещать адрес, которого нет, хуже, чем показать
 * локальный.
 */
export function publicMemoryUrl(host: string, proto: string): string {
  if (!host) return "http://127.0.0.1:3700";
  return `${proto}://${host}`;
}

/**
 * Публичный адрес соседней службы — служба чата (186-4).
 *
 * 🔒 ТОТ ЖЕ ВЫВОД, ЧТО У ВХОДА И У САЙТА, И ЖИВЁТ ОН ЗДЕСЬ ЖЕ: два места,
 * считающие один адрес, расходятся так, что одна половина продолжает работать.
 * 🛑 Пустая строка — законный ответ: подвал тогда не рисует ссылку вовсе.
 */
export function publicChatUrl(host: string, proto: string): string {
  return siblingByHost(host, proto, "chat.", "3600");
}
