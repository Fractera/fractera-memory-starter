//
// 🔒 РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-16, ДОСЛОВНО: «в каждой микро сервисе стандартный
// конфиг: реестр микросервисов сервера… во всех микро сервисах будет абсолютно
// одинаково… типизированные название, API этого микро servis са и описание что
// он делает все на английском языке всегда, идентификатор автора, цена для
// продажи, доступен для продажи или нет». Наполняется пока руками.
//
// 🔒 ПАМЯТИ НУЖНО ОТТУДА РОВНО ОДНО — `id`, типизированное имя службы. Оно и есть
// закрытый список ПЕРВЫХ сегментов пути источника (207-2). Остальные поля память
// не читает и не правит: файл общий, и урезать его под себя значило бы завести
// вторую версию реестра, которая разойдётся с первой молча.
//
// 🛑 ФАЙЛ ЧИТАЕТСЯ ОДИН РАЗ ЗА ЖИЗНЬ ПРОЦЕССА. Он меняется руками и редко;
// перечитывать его на каждом запросе значило бы платить диском за то, что не
// меняется. Правка требует перезапуска — это сказано здесь, чтобы следующий не
// искал, почему новая служба «не видна».

import { readFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

/** Где лежит реестр: КОРЕНЬ дерева службы, рядом с `package.json`. */
export const SERVICES_PATH =
  process.env.SERVICES_FILE ?? join(dirname(fileURLToPath(import.meta.url)), "..", "SERVICES.json")

/**
 * Разобранный реестр. Файла нет или он кривой — пустой список и причина; служба
 * при этом продолжает работать, а незнакомым становится ЛЮБОЕ имя.
 *
 * 🔒 ПУСТОЙ РЕЕСТР ЗАКРЫВАЕТ ВХОД, А НЕ ОТКРЫВАЕТ ЕГО. Обратное решение —
 * «нет файла, значит пускаем всех» — превращает потерю конфига в тихую дыру.
 */
function load() {
  try {
    const raw = JSON.parse(readFileSync(SERVICES_PATH, "utf8"))
    const list = Array.isArray(raw?.services) ? raw.services : []
    return { error: null, root: raw?.root ?? null, services: list, updated: raw?.updated ?? null }
  } catch (e) {
    return { error: String(e.message).slice(0, 200), root: null, services: [], updated: null }
  }
}

const REGISTRY = load()

/**
 * Какая служба стоит в КОРНЕ домена (211-5): она отвечает и по <домену>, и по своему субдомену.
 *
 * 🔒 УКАЗАТЕЛЬ, А НЕ ВТОРАЯ КОПИЯ ЗАПИСИ — решение владельца. Передать корень другой службе значит
 * поменять одно слово в общем файле; запись самой службы при этом остаётся одна.
 */
export const ROOT_SERVICE = REGISTRY.root

/** Стоит ли эта служба в корне домена. */
export function isRoot(id) {
  return Boolean(id) && id === REGISTRY.root
}

/** Записи реестра как есть — для страниц и приборов, не для проверки. */
export const SERVICES = REGISTRY.services

/** Почему реестр пуст, если он пуст. Пустая причина значит «всё в порядке». */
export const SERVICES_ERROR = REGISTRY.error

/** Типизированные имена служб — закрытый список первых сегментов пути источника. */
export function serviceIds() {
  return SERVICES.map((s) => s.id).filter((id) => typeof id === "string" && id.length > 0)
}

/**
 * Знает ли сервер такую службу.
 *
 * 🔒 СРАВНЕНИЕ ТОЧНОЕ, БЕЗ ПРИВЕДЕНИЯ РЕГИСТРА И БЕЗ ПОХОЖЕСТИ. Имя службы едет
 * в значение колонки и в условие запроса; «почти совпало» здесь означало бы, что
 * `Data` и `data` — две разные службы в отчётах и одна в проверке.
 */
export function isKnownService(id) {
  return typeof id === "string" && serviceIds().includes(id)
}

/** Запись службы целиком — когда нужен её адрес или описание, а не факт знакомства. */
export function serviceById(id) {
  return SERVICES.find((s) => s.id === id) ?? null
}

// ── КАНАЛЫ СЛУЖБЫ (226-1) ───────────────────────────────────────────────────
//
// 🎯 СЛОВО ВЛАДЕЛЬЦА 2026-09-18: «у каждого микросервиса внутри должен быть объект каналы и внутри
// каналов объект сейчас Telegram… Это нужно для того чтобы один микросервис мог показать прямую
// ссылку и позволить пользователю перейти из одного бота в другой».
//
// 🔒 РОД КАНАЛА — ЗАКРЫТЫЙ СПИСОК, КАК РОД АВТОРИЗАЦИИ. Открытый ключ означал бы, что завтра в
// реестре появятся `whatsapp`, `whats_app` и `wa` как три разных канала, и ни один сторож этого не
// заметит: каждый из них — «просто строка».
export const CHANNEL_KINDS = ["telegram"]

/** Каналы службы: `{ telegram: { bot, url } }`. Нет каналов — пустой объект, а не null. */
export function channelsOf(id) {
  const c = serviceById(id)?.channels
  return c && typeof c === "object" ? c : {}
}

/**
 * Прямая ссылка службы в названном канале — или `null`.
 *
 * 🔒 ССЫЛКА ХРАНИТСЯ ЦЕЛИКОМ И НЕ СОБИРАЕТСЯ ИЗ ИМЕНИ БОТА. Тот же закон, что «адрес ресурса берётся
 * из страницы, а не собирается по шаблону»: `t.me/<имя>` верно ровно до первого бота, живущего по
 * другому адресу, и ошибка эта молчит — ссылка выглядит настоящей.
 */
export function channelLink(id, kind) {
  const url = channelsOf(id)?.[kind]?.url
  return typeof url === "string" && url ? url : null
}

/**
 * Каким каналом, судя по всему, пришла просьба от службы-источника.
 *
 * 🛑 ЭТО ВЫВОД, А НЕ ФАКТ, И ПОТОМУ ОН СДЕЛАН САМЫМ ОСТОРОЖНЫМ СПОСОБОМ. Канала во входящем вызове
 * сегодня НЕТ: путь источника устроен как `<служба>/<что угодно>`, и слово «telegram» стоит в нём то
 * вторым сегментом, то не стоит вовсе. Разбирать середину пути значило бы угадывать, а цена промаха —
 * ссылка не туда.
 * 🔒 ПОЭТОМУ: у службы-источника ровно один канал — считаем, что просьба пришла им; каналов ноль или
 * больше одного — `null`, и ответ уедет веб-адресом. **Неизвестный канал обязан давать прежнее
 * поведение, а не пустую ссылку.**
 */
export function channelOfService(id) {
  const kinds = Object.keys(channelsOf(id)).filter((k) => CHANNEL_KINDS.includes(k))
  return kinds.length === 1 ? kinds[0] : null
}
