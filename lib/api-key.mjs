// 🔒 ЗАЧЕМ ОН НУЖЕН, ЕСЛИ ЕСТЬ СЕКРЕТ МАШИНЫ. Секрет `DATA_SECRET` — общий на
// все службы этого сервера: им ходят слой данных, бот, панель. Отдать его
// наружу значит отдать чужаку всё сразу и лишиться возможности отозвать доступ,
// не сломав при этом половину машины. Ключ памяти отзывается одной кнопкой и
// касается только памяти.
//
// 🔒 КЛЮЧ ОДИН, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-11, ДОСЛОВНО: «у нас будет один
// ключ на все действия». Чтение и запись им обоими; раздельных прав нет — и не
// надо делать вид, что есть.
//
// 🛑 НОВЫЙ КЛЮЧ ОТМЕНЯЕТ ПРЕЖНИЙ, ДРУГОГО ОТЗЫВА НЕТ. Это говорится человеку
// словами на экране: «сгенерировать» и «отозвать» здесь одно и то же действие,
// и тот, кто этого не знал, ломает работающую интеграцию нажатием кнопки.
//
// 🔒 ФАЙЛ, А НЕ БАЗА, И ПРИЧИНА МЕХАНИЧЕСКАЯ: ключ проверяется на КАЖДОМ запросе
// к `/v1/*`, в том числе тогда, когда слой данных недоступен. Ключ, за которым
// надо ходить в базу, перестаёт работать ровно в тот момент, когда он нужнее
// всего — при разборе отказа.

import { chmodSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname } from "node:path"
import { randomBytes, timingSafeEqual } from "node:crypto"

/** Где лежит ключ. Своё место, а не общий файл секретов машины. */
export const KEY_PATH = process.env.MEMORY_API_KEY_FILE ?? "/etc/fractera/memory-api-key"

/** Приставка, по которой ключ узнаётся глазом в логе и в чужом конфиге. */
const PREFIX = "fmk_"

/** Прочитать ключ с диска. Нет файла — ключа нет, и это законное состояние. */
export function readKey() {
  try {
    const raw = readFileSync(KEY_PATH, "utf8").trim()
    return raw || null
  } catch {
    return null
  }
}

/**
 * Родить новый ключ и положить его на место прежнего.
 *
 * 🔒 32 БАЙТА СЛУЧАЙНОСТИ, А НЕ «ЧИТАЕМАЯ ФРАЗА»: ключ набирают не руками, его
 * копируют. Читаемость здесь покупалась бы угадываемостью.
 * 🛑 ПРАВА `0600` СТАВЯТСЯ ЯВНО И ДО ЗАПИСИ СОДЕРЖИМОГО НЕ ПРОВЕРЯЮТСЯ НИКЕМ:
 * файл, доступный на чтение кому попало, — это и есть утечка ключа.
 */
export function rotateKey() {
  const key = PREFIX + randomBytes(32).toString("base64url")
  try {
    mkdirSync(dirname(KEY_PATH), { recursive: true })
  } catch { /* папка есть — хорошо */ }
  writeFileSync(KEY_PATH, key + "\n", { mode: 0o600 })
  try {
    chmodSync(KEY_PATH, 0o600)
  } catch { /* файловая система без прав — скажет сама при чтении */ }
  return key
}

/**
 * Тот ли это ключ.
 *
 * 🔒 СРАВНЕНИЕ ПОСТОЯННОГО ВРЕМЕНИ, А НЕ `===`. Обычное сравнение строк
 * заканчивается на первом несовпавшем знаке, и по времени ответа ключ
 * подбирается знак за знаком. Это дёшево сделать правильно и дорого объяснять
 * потом.
 */
export function keyMatches(given) {
  const real = readKey()
  if (!real || typeof given !== "string" || !given) return false
  const a = Buffer.from(given)
  const b = Buffer.from(real)
  if (a.length !== b.length) return false
  try {
    return timingSafeEqual(a, b)
  } catch {
    return false
  }
}

/**
 * Как показать ключ человеку, не показывая его целиком.
 *
 * 🔒 НА ЭКРАНЕ ЖИВЁТ МАСКА, А ПОЛНЫЙ КЛЮЧ ВИДЕН РОВНО ОДИН РАЗ — в ответе на
 * нажатие кнопки. Ключ, который можно подсмотреть на чужом экране в любой
 * момент, перестаёт быть секретом; маски же хватает, чтобы узнать «тот ли он».
 */
export function maskKey(key) {
  if (!key) return null
  const tail = key.slice(-4)
  return `${PREFIX}…${tail}`
}
