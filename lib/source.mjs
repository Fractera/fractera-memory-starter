import { isKnownService } from "./services.mjs"

/** Разделитель внутри хранимой строки: машинный. Человеку путь печатается через « › ». */
export const SEP = "/"

/**
 * Первый сегмент строк, пришедших ДО этого шага. Не служба и не имя: честная
 * пометка «происхождение неизвестно».
 *
 * 🔒 ВЫДУМАННЫЙ ИСТОЧНИК БЫЛ БЫ ЛОЖЬЮ О ПРОИСХОЖДЕНИИ, а пустое поле через месяц
 * неотличимо от недосмотра. `legacy` говорит правду и ищется одним запросом.
 */
export const LEGACY = "legacy"

/** Сколько уровней имеет смысл: служба, её сущность, её сущность… Дальше это уже не адрес, а рассказ. */
const MAX_DEPTH = 6
const MAX_SEGMENT = 64

/**
 * Привести один сегмент к виду, годному для колонки и для сравнения.
 * Пробелы становятся дефисом, регистр опускается, `/` запрещён — иначе один
 * сегмент притворился бы двумя.
 */
function normalise(raw) {
  return String(raw ?? "")
    .trim()
    .toLowerCase()
    .replace(/[\s_]+/g, "-")
    .replace(/[^a-z0-9.@-]/g, "")
    .slice(0, MAX_SEGMENT)
}

/**
 * Разобрать присланный источник.
 *
 * Принимает список (`["chat","telegram-bot","roma-armstrong"]`) или строку
 * (`"chat/telegram-bot/roma-armstrong"`) — второе потому, что так его удобно
 * класть в форму и в заголовок, а не потому, что мы любим два пути.
 *
 * @returns {{ok:true, path:string[], text:string} | {ok:false, error:string, why:string}}
 */
export function parseSource(from) {
  const raw = Array.isArray(from) ? from : String(from ?? "").split(SEP)
  const path = raw.map(normalise).filter(Boolean)

  if (path.length === 0) {
    return { error: "source-required", ok: false, why: "источник не назван: первым сегментом идёт имя службы" }
  }
  if (path.length > MAX_DEPTH) {
    return { error: "source-too-deep", ok: false, why: `сегментов ${path.length}, предел ${MAX_DEPTH}` }
  }
  // 🔒 СРАВНЕНИЕ С РЕЕСТРОМ ТОЧНОЕ: «похоже на службу» здесь означало бы, что
  // опечатка заводит двойника, и половина записей уезжает к нему.
  if (!isKnownService(path[0])) {
    return {
      error: "unknown-service",
      ok: false,
      why: `службы «${path[0]}» нет в реестре сервера (SERVICES.json)`,
    }
  }
  return { ok: true, path, text: path.join(SEP) }
}

/** Путь для человеческого глаза: `chat › telegram-bot › roma-armstrong`. */
export function printSource(text) {
  return String(text ?? "").split(SEP).filter(Boolean).join(" › ")
}

/** Первый сегмент хранимого пути — служба. Нужен группировке «кто мне писал». */
export function serviceOf(text) {
  return String(text ?? "").split(SEP)[0] ?? ""
}

/**
 * Каким ключом пришёл зовущий: секретом машины или ключом памяти.
 *
 * 🛑 СВЯЗАТЬ ПУТЬ С КЛЮЧОМ СЕГОДНЯ НЕЛЬЗЯ, И ЭТО ИЗМЕРЕНО, А НЕ ЗАБЫТО.
 * Секрет машины `DATA_SECRET` — ОДИН на все службы сервера: им ходят и слой
 * данных, и бот, и панель. Значит по ключу невозможно отличить `data` от
 * `telegram`, и проверка «чужой не может назваться службой» была бы театром.
 * Что достижимо — то и делается: род предъявителя записывается рядом с путём,
 * и расхождение видно разбирающему. Настоящая привязка требует своего ключа у
 * каждой службы; это решение владельца, а не правка.
 */
export const AUTH = { KEY: "key", MACHINE: "machine" }
