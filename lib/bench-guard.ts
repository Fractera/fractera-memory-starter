import { machineEnv } from "@/lib/fractera/machine-env"
import { fracteraSession } from "@/lib/fractera/session"

// ПРИВРАТНИК ДВЕРЕЙ СТЕНДА: СЕССИЯ ЧЕЛОВЕКА ИЛИ КЛЮЧ ПАМЯТИ (189-3).
//
// 🎯 ЗАЧЕМ ЗАВЕДЁН. Страница стенда закрыта ролью `architect`, и это правильно —
// но из-за этого ПРИБОР не может прогнать её двери: у скрипта нет куки, и он
// получает переадресацию на вход. Два подшага подряд закрывались косвенной
// плоскостью — «собранное дерево на сервере» вместо настоящего вызова.
//
// 🔒 РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-12: не снимать защиту, а научить двери стенда
// принимать тот ключ, который у памяти УЖЕ есть. Его слова на предложение
// открыть сервер в режиме без авторизации — выбран второй путь, «на будущее»,
// ради воспроизводимых машинных замеров.
//
// ✗ ЗДЕСЬ БЫЛ КЛЮЧ ПАМЯТИ, И ЭТО БЫЛА ОШИБКА — НАЙДЕНА ВЛАДЕЛЬЦЕМ 2026-09-12.
// Его вопрос: «если у нас в проекте существует только один стандарт передачи
// данных, значит этого стандарта мы и должны придерживаться — неважно, решение
// это внутри стенда или снаружи проекта».
//
// 🔒 ЧТО ИМЕННО БЫЛО СЛОМАНО. Ключ памяти выдают ЧУЖИМ инструментам, и снаружи
// им открываются ровно два глагола договора — в этом весь чёрный ящик. Пустив
// тот же ключ в двери стенда, я дал наружу ВТОРУЮ дверь, которой в договоре
// нет: через неё чужой мог бы обратиться прямо к графу, минуя `recall`.
// 🛑 Ошибка была НЕ в том, что стенд смотрит внутрь ящика — прибор обязан
// щупать хранилища по отдельности, иначе он меряет ящик целиком и не может
// сказать, что сработало. Ошибка была в том, ЧЕМ он открывается.
//
// 🔒 РАЗДЕЛЕНИЕ, КОТОРОЕ У ПРОЕКТА УЖЕ ЕСТЬ И КОТОРОЕ Я НЕ ПРИМЕНИЛ:
//   • секрет машины `DATA_SECRET` — СВОИМ процессам на этом сервере (приборы);
//   • ключ памяти `x-memory-key` — ЧУЖИМ инструментам, и только на `/v1/*`.
// Оно записано в `server.mjs` и действует на договоре с шага 185; стенд просто
// остался в стороне.
//
// 🛑 ЧЕГО ЭТОТ ПРИВРАТНИК НЕ ДЕЛАЕТ: он не открывает СТРАНИЦУ. Экран живёт под
// ролью `architect`; секретом машины открываются только двери стенда, то есть
// то, что зовут приборы, а не то, что смотрит человек.

export type BenchWho = { by: "machine" | "session"; email?: string }

/**
 * Секрет машины — тот же, которым служба ходит в слой данных.
 *
 * 🔒 СВОЙ ПРОЦЕСС ОТ ЧУЖОГО ИНСТРУМЕНТА ОТЛИЧАЕТ РОВНО ОДНО: доступ к файлу
 * секретов на этой машине. Чужому инструменту его не выдают никогда — значит
 * снаружи в двери стенда не войти, даже имея ключ памяти.
 */
function machineSecret(): string {
  return process.env.DATA_SECRET || machineEnv("DATA_SECRET") || ""
}

/** Постоянное по времени сравнение: обычное выдаёт секрет по времени ответа. */
function sameSecret(given: string): boolean {
  const real = machineSecret()
  if (!real || !given || given.length !== real.length) return false
  let diff = 0
  for (let i = 0; i < real.length; i += 1) diff |= real.charCodeAt(i) ^ given.charCodeAt(i)
  return diff === 0
}

/**
 * Пустить или отказать.
 *
 * Возвращает `{ denied }` с готовым ответом, когда пускать нельзя, и `{ who }`,
 * когда можно. 🔒 Отказы РАЗНЫЕ и названы по-разному: `unauthorized` значит «я
 * тебя не знаю», `forbidden` — «знаю, но роль не та». Один код на оба заставил
 * бы человека гадать, входить ему заново или просить прав.
 */
export async function benchGuard(
  request: Request,
): Promise<{ denied: NextResponse; who?: never } | { denied?: never; who: BenchWho }> {
  // 🔒 ЗАГОЛОВОК ТОТ ЖЕ, ЧТО У СЛОЯ ДАННЫХ (`x-data-secret`), И ЭТО НЕ СЛУЧАЙНО:
  // один секрет — одно имя во всём проекте. Второе имя для того же секрета
  // однажды разошлось бы с первым, и половина вызовов молча перестала бы
  // проходить.
  if (sameSecret(request.headers.get("x-data-secret") ?? "")) {
    return { who: { by: "machine" } }
  }

  const session = await fracteraSession()
  if (!session) {
    return { denied: NextResponse.json({ error: "unauthorized", ok: false }, { status: 401 }) }
  }
  if (!session.roles.includes("architect")) {
    return { denied: NextResponse.json({ error: "forbidden", ok: false }, { status: 403 }) }
  }
  return { who: { by: "session", email: session.email } }
}
