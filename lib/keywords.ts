import { labelSearch } from "@/lib/fractera/knowledge";

// ОТКУДА БЕРУТСЯ КЛЮЧЕВЫЕ СЛОВА ДЛЯ ГРАФА (189-4).
//
// 🎯 ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ СУЩЕСТВУЕТ. Не дай графу слов — он вытащит их сам,
// вызовом `gpt-4o-mini`, и «дешёвый третий уровень» молча станет платным.
// Измерено: 3538 мс против 666 мс. Значит слова обязан назвать тот, кто
// спрашивает, и делать это без модели — иначе мы заменим один ход другим.
//
// 🔒 ДВА СПИСКА, И РАЗНИЦА НЕ КОСМЕТИЧЕСКАЯ. `hl_keywords` — о ЧЁМ вопрос в
// целом (темы), `ll_keywords` — КАКИЕ именно вещи названы (сущности). Движок
// ищет ими по-разному: первым — связи и темы, вторым — узлы. Слить их в один
// список значило бы отдать ему решать за нас.
//
// 🔒 СЛОВА ИЗ ВОПРОСА ПЛЮС МЕТКИ, КОТОРЫЕ ГРАФ УЖЕ ЗНАЕТ. Первое даёт точность
// формулировки, второе — попадание в настоящие имена сущностей: человек пишет
// «денис», а в графе лежит «Денис Соколов».
//
// 🛑 ДВИЖОК НЕ УМЕЕТ ПАДЕЖЕЙ, И ЭТО ИЗМЕРЕНО У СОСЕДА: `Зеленодольске` → [],
// `Денис` → [] при живой метке `Дений Парадоксу`. Значит нестрогость наша:
// ищем по ОСНОВЕ слова, отрезая хвост, а не по слову целиком.

/**
 * Служебные слова, которые ключевыми не бывают никогда.
 *
 * 🔒 СПИСОК КОРОТКИЙ НАМЕРЕННО. Длинный словарь стоп-слов — это второй словарь,
 * который разойдётся с языком; здесь достаточно выбросить то, что заведомо не
 * называет ни темы, ни вещи.
 */
const STOP = new Set([
  "а", "бы", "был", "была", "было", "были", "в", "во", "все", "да", "для", "до", "его", "ещё",
  "же", "за", "и", "из", "или", "к", "как", "кто", "ли", "мне", "мой", "моя", "мои", "на", "не",
  "него", "ни", "но", "о", "об", "он", "она", "они", "от", "по", "с", "со", "так", "то", "у",
  "что", "чей", "чём", "это", "я",
  "a", "an", "and", "are", "as", "at", "be", "by", "for", "from", "he", "her", "his", "how",
  "i", "in", "is", "it", "its", "me", "my", "of", "on", "or", "our", "she", "that", "the",
  "their", "they", "this", "to", "was", "were", "what", "when", "where", "which", "who", "with",
]);

/** Слова вопроса: длиннее двух знаков, не служебные, без повторов. */
export function wordsOf(text: string): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of String(text ?? "").toLowerCase().split(/[^\p{L}\p{N}]+/u)) {
    if (raw.length < 3 || STOP.has(raw) || seen.has(raw)) continue;
    seen.add(raw);
    out.push(raw);
  }
  return out;
}

/**
 * Основа слова — грубо, отрезанием хвоста.
 *
 * 🛑 ПРИЁМ ГРУБЫЙ НАМЕРЕННО, И ЭТО НЕ ЛЕНЬ. Настоящая лемматизация потребовала
 * бы словаря или модели; первое — вторая копия языка, второе — тот самый ход
 * модели, ради устранения которого всё и делается. Ошибка грубой основы дёшева:
 * лишний кандидат в метки отсеется поиском, которого он не найдёт.
 */
const stem = (w: string) => (w.length > 5 ? w.slice(0, Math.max(4, w.length - 2)) : w);

export type Keywords = {
  /** Темы — о чём вопрос. */
  high: string[];
  /** Вещи — какие имена названы; сюда же попадают настоящие метки графа. */
  low: string[];
  /** Какие метки графа удалось узнать в словах вопроса. */
  matched: string[];
};

/**
 * Собрать ключевые слова к вопросу.
 *
 * 🔒 МОДЕЛЬ ЗДЕСЬ НЕ ЗОВЁТСЯ ВОВСЕ. Поиск метки в графе — это запрос к его
 * списку имён: измерено у соседа, весь список 280 мс, одна метка 41 мс, ходов
 * модели ноль.
 * 🛑 ПОИСК МЕТОК ОГРАНИЧЕН ЧИСЛОМ СЛОВ: иначе длинный вопрос превратился бы в
 * два десятка запросов, и дешёвый уровень стал бы медленным по другой причине.
 */
export async function keywordsFor(question: string): Promise<Keywords> {
  const words = wordsOf(question);
  const matched: string[] = [];

  for (const w of words.slice(0, 6)) {
    const found = await labelSearch(stem(w), 3);
    for (const label of found) {
      if (!matched.includes(label)) matched.push(label);
    }
  }

  return {
    high: words.slice(0, 8),
    // Настоящие имена сущностей идут первыми: по ним движок находит узлы точно.
    low: [...matched, ...words].slice(0, 10),
    matched,
  };
}
