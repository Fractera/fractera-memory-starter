// Наш внутренний псевдотип `value` уехал через этот импорт в схему инструмента
// агента, API Anthropic её отверг — и `memory_write` был недостижим СУТКИ, при
// том что `tools/list` показывал все двенадцать инструментов, а дверь отвечала
// `ok:true`. Две вещи, которые не должны знать друг о друге, сломались вместе.

/**
 * Версия договора. Меняется по правилам semver:
 * major — сломали существующий метод · minor — добавили метод · patch — правка текста.
 *
 * 🔒 ВЕРСИЯ ЕСТЬ С ПЕРВОГО ДНЯ, А НЕ «КОГДА ПОНАДОБИТСЯ». Служба без версии —
 * служба, которую нельзя менять, не ломая потребителя: он не сможет ни узнать
 * о смене, ни объяснить свой отказ.
 */
export const CONTRACT_VERSION = "1.1.0"

/** Имя службы — как она называет себя сама, а не как её зовёт кто-то снаружи. */
export const SERVICE = "fractera-memory"

/**
 * МЕТОДЫ — ДВА: сказать и спросить (подшаг 175-2).
 *
 * 🪦 В 175-1 ЗДЕСЬ БЫЛ НОЛЬ, и это было правильным состоянием: пустой договор
 * лучше договора, обещающего непостроенное. Метод, который виден и не работает,
 * тратит ход модели на вызов и ход на разбор отказа.
 *
 * 🔒 ПОЧЕМУ ИХ ИМЕННО ДВА. Запись меняет состояние, чтение нет — слить их в
 * один «расскажи памяти что-нибудь» значило бы потерять и повторяемость, и
 * безопасность. Больше двух наружу не нужно: всё остальное — внутренние
 * решения ящика.
 *
 * 🛑 ЧИСЛО В ЭТОМ КОММЕНТАРИИ ПРАВИТСЯ ВМЕСТЕ СО СПИСКОМ. Рукописное число не
 * двигается само никогда — в проекте это оплачено четырежды за три дня, и
 * дважды автором закона об этом.
 */
export const METHODS = [
  {
    name: "remember",
    about:
      "Сказать памяти то, что сказал человек — обычной фразой, как он её произнёс. " +
      "Куда это ляжет, заводить ли новое место и что делать с противоречием — решает память.",
    params: [
      { name: "who", type: "string", required: true, about: "Кто говорит: устойчивый ключ человека" },
      { name: "text", type: "string", required: true, about: "Фраза человека как есть, без пересказа" },
    ],
    returns:
      "what_happened — словами, которые можно произнести человеку; noted — что именно записано, " +
      "с from_table и claim у каждой записи. " +
      "При противоречии сказано «было X, стало Y»: последнее побеждает, но вслух.",
    onMiss:
      "Фактов о человеке во фразе нет — ok:true и пустой noted, это не ошибка. " +
      "Если разобрать нельзя, приходит refusal с причиной: кончились деньги, ключ отвергнут или модель недоступна.",
  },
  {
    name: "recall",
    about:
      "Спросить память о человеке. Без вопроса отдаёт всё, что знает, — это мгновенно и не стоит вызова модели. " +
      "С вопросом сначала ищет механически.",
    params: [
      { name: "who", type: "string", required: true, about: "О ком спрашиваем" },
      { name: "text", type: "string", required: false, about: "Вопрос человеческой фразой. Без него придёт всё" },
    ],
    returns:
      "known — что известно; у каждого значения есть from_table (какая таблица дала ответ), " +
      "claim (сказано человеком или выведено) и basis (из чего выведено). " +
      "not_yet_known — чего не хватает и почему это важно; used_model — звалась ли модель. " +
      "🛑 Имя таблицы называется в ОТВЕТЕ и не принимается в вопросе: где искать, решает память.",
    onMiss:
      "О человеке ничего не записано — ok:true и пустой known. " +
      "Вопрос не совпал ни с чем известным — приходит всё известное и сказано, что точного совпадения нет.",
  },
]

/**
 * Договор в том виде, в каком его отдаёт `GET /v1/contract`.
 *
 * 🔒 ОТДАЁТСЯ ПОРОЖДЁННОЕ, А НЕ ВТОРАЯ РУКОПИСНАЯ КОПИЯ. Список, написанный
 * руками рядом с кодом, расходится с ним молча — в этом проекте измерено
 * четырежды за три дня («пять инструментов» при шести папках и так далее).
 */
export function contract() {
  return {
    service: SERVICE,
    version: CONTRACT_VERSION,
    methods: METHODS.map((m) => ({
      about: m.about,
      name: m.name,
      onMiss: m.onMiss,
      params: m.params,
      returns: m.returns,
    })),
  }
}
