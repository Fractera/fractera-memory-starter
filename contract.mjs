// «мы делаем память как чёрный ящик, который должен принимать и возвращать
// данные, и те процессы, которые у них происходят внутри, она должна
// производить внутри самостоятельно. То есть это не агент какой-то снаружи
// должен уметь это делать… Агент снаружи говорит: на тебе это и сделай то, что
// надо».
//
// Отсюда: снаружи виден ТОЛЬКО этот файл. Сколько внутри хранилищ, есть ли
// реестр, когда заводится таблица — частное дело службы, и в договоре этого
// нет и не будет.
