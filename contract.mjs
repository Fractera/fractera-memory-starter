/**
 * Версия договора. Меняется по правилам semver:
 * major — сломали существующий метод · minor — добавили метод · patch — правка текста.
 *
 * 🔒 ВЕРСИЯ ЕСТЬ С ПЕРВОГО ДНЯ, А НЕ «КОГДА ПОНАДОБИТСЯ». Служба без версии —
 * служба, которую нельзя менять, не ломая потребителя: он не сможет ни узнать
 * о смене, ни объяснить свой отказ.
 */
export const CONTRACT_VERSION = "1.0.0"

/** Имя службы — как она называет себя сама, а не как её зовёт кто-то снаружи. */
export const SERVICE = "fractera-memory"

/**
 * МЕТОДЫ. Сейчас их НОЛЬ, и это правильное состояние (подшаг 175-1).
 *
 * 🔒 ПУСТОЙ ДОГОВОР ЛУЧШЕ ДОГОВОРА, ОБЕЩАЮЩЕГО НЕПОСТРОЕННОЕ. Метод, который
 * виден и не работает, хуже отсутствующего: он тратит ход модели на вызов и
 * ход на разбор отказа. Этот закон в проекте уже оплачен — дверь знаний 160-6
 * работала сутки, а инструмента, который инструкция велела звать, не было
 * вовсе.
 *
 * 🎯 УКАЗАНИЕ ВЛАДЕЛЬЦА 2026-09-09: «сначала сделай под неё место, а потом
 * подумаем, что самое простое с одной стороны, фундаментальное с другой
 * стороны, способное дать первый результат, может сделать». Наполнять этот
 * список будем по одному методу, осознанно, вместе.
 *
 * Форма записи, когда методы появятся:
 *   {
 *     name: "…",            // как зовётся снаружи
 *     about: "…",           // когда звать — словами, а не типами
 *     params: [ { name, type, required, about } ],
 *     returns: "…",         // что придёт назад
 *     onMiss: "…",          // что придёт, если не вышло, и что с этим делать
 *   }
 */
export const METHODS = []

/**
 * Договор в том виде, в каком его отдаёт `GET /v1/contract`.
 *
 * 🔒 ОТДАЁТСЯ ПОРОЖДЁННОЕ, А НЕ ВТОРАЯ РУКОПИСНАЯ КОПИЯ. Список, написанный
 * руками рядом с кодом, расходится с ним молча — в этом проекте измерено
 * четырежды за три дня («пять инструментов» при шести папках и так далее).
 */
export function contract() {
  return {
    service: SERVICE,
    version: CONTRACT_VERSION,
    methods: METHODS.map((m) => ({
      about: m.about,
      name: m.name,
      onMiss: m.onMiss,
      params: m.params,
      returns: m.returns,
    })),
  }
}
