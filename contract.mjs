// Схемы инструментов агента приходят из `GET /v1/contract` ПО HTTP, а не
// импортом файла. Пока схема берётся импортом — отдельность есть
// договорённость; когда по HTTP — факт.
// ✗ ОПЛАЧЕНО 2026-09-09: `scripts/agent/intake-preloader.js:721` в репозитории
