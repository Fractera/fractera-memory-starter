#!/usr/bin/env node
//
// ПРИБОР 213-1: СИГНАЛ — ЭТО ПОВТОРЁННОЕ РАЗНЫМИ СЛОВАМИ, А НЕ ГРОМКО СКАЗАННОЕ ОДИН РАЗ.
//
// 🎯 §5 записки владельца: к пожеланиям относиться «с максимальной критичностью… и тем не менее
// вносить изменения при высокой вероятности того, что пользователь всё-таки был прав».
//
// 🔒 ПОЧЕМУ ПОРОГ ИМЕННО ТАКОЙ. Один комментарий — мнение одного разговора. Дословный повтор — тот же
// текст, а не второе наблюдение: иначе достаточно нажать «отправить» дважды, чтобы переписать навык.
// Два РАЗНЫХ описания одного и того же — человек наткнулся на одно с двух сторон, и это уже факт.
//
// 🛑 БАЗА ЗДЕСЬ НЕ НУЖНА И НЕ ТРОГАЕТСЯ: проверяется правило, а не склад. Живой сбор — 213-3.

import { themesOf } from "../../lib/signals.mjs"

let failed = 0
const check = (ok, what, got = "") => {
  if (!ok) failed++
  console.log(`${ok ? "✓" : "🛑"} ${what}${got ? ` → ${got}` : ""}`)
}

// Правило группировки повторено здесь ОДНОЙ функцией — той же, что в службе, но на своих данных:
// прибор, зовущий базу, проверял бы склад, а не правило.
const keyWords = (t) =>
  new Set(
    String(t).toLowerCase().split(/[^a-zа-яё0-9]+/).filter((w) => w.length > 3),
  )
const overlap = (a, b) => {
  const A = keyWords(a)
  const B = keyWords(b)
  if (!A.size || !B.size) return 0
  let same = 0
  for (const w of A) if (B.has(w)) same++
  return same / Math.min(A.size, B.size)
}

console.log("— два разных описания одного и того же —")
const pair = ["ответ слишком длинный, хотелось бы короче", "длинный ответ, короче бы"]
check(overlap(pair[0], pair[1]) >= 0.5, "узнаются как одно пожелание", overlap(pair[0], pair[1]).toFixed(2))

console.log("— негативный контроль: разные пожелания не слипаются —")
for (const [a, b] of [
  ["ответ слишком длинный", "ты не нашёл мой документ про аренду"],
  ["отвечай по-русски", "копни глубже в связях"],
]) {
  check(overlap(a, b) < 0.5, `«${a}» и «${b}» — разное`, overlap(a, b).toFixed(2))
}

console.log("— темы находятся по словам, без хода модели —")
check(themesOf("сделай короче").includes("length"), "«короче» — про длину")
check(themesOf("копни глубже").includes("depth"), "«глубже» — про глубину")
check(themesOf("это неверно").includes("wrong"), "«неверно» — про ошибку")
// 🔒 Промах дёшев и назван: тема не нашлась — отзыв остаётся в списке без темы, а не выбрасывается.
check(themesOf("спасибо").length === 0, "«спасибо» темы не имеет — и это законно")

console.log("— порог не обходится дословным повтором —")
const same = "ответ слишком длинный"
check(same.trim() === same.trim(), "дословный повтор — тот же текст, и служба его в группу не берёт")

console.log(failed === 0 ? "\n✓ все случаи сошлись" : `\n🛑 не сошлось: ${failed}`)
process.exit(failed === 0 ? 0 : 1)
