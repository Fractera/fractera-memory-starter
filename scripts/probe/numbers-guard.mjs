// ПРИБОР 208-6: НЕГАТИВНЫЙ КОНТРОЛЬ СТОРОЖА ЧИСЕЛ.
//
// 🔒 ЗАЧЕМ ОН НУЖЕН, ОПЛАЧЕНО В ЭТОМ ЖЕ ПОДШАГЕ: первая редакция сторожа использовала `\b` после
// кириллицы — граница ASCII-слова, которая после русской буквы не срабатывает НИКОГДА. Сторож нашёл
// ноль нарушений при четырнадцати настоящих и бодро напечатал «числа сходятся».
// 🛑 ОТСЮДА ПРАВИЛО: у сторожа обязан быть свой негативный контроль, иначе он зелен по причине
// собственной слепоты, а не по причине порядка в доме.

import { problemsIn, truths } from "../check-numbers.mjs"

let failed = 0
const check = (ok, what, got = "") => {
  if (!ok) failed++
  console.log(`${ok ? "✓" : "🛑"} ${what}${got ? ` → ${got}` : ""}`)
}

const counts = truths()
console.log(`правда кода: глаголов ${counts.глагол}, навыков ${counts.навык}, разделов ${counts.раздел}, родов ${counts.род}`)

console.log("— сторож обязан ВИДЕТЬ ложь —")
check(problemsIn("// у стенда два глагола", "x.mjs", counts).length === 1, "«два глагола» при трёх — поймано")
check(problemsIn("// РАЗДЕЛОВ ПЯТЬ", "x.mjs", counts).length === 1, "«разделов пять» при девяти — поймано")
check(problemsIn("// родов шесть", "x.mjs", counts).length === 1, "«родов шесть» при десяти — поймано")

console.log("— и обязан МОЛЧАТЬ на правде —")
check(problemsIn("// глаголов три", "x.mjs", counts).length === 0, "верное число не тревожит")
check(problemsIn("// ДВА раздельных факта", "x.mjs", counts).length === 0, "«раздельных» — не «разделов»")
check(problemsIn("// 🪦 РАЗДЕЛОВ ДЕСЯТЬ С 195-1", "x.mjs", counts).length === 0, "надгробие говорит о прошлом и не правится")
check(problemsIn("/** Один навык — только из списка. */", "x.mjs", counts).length === 0, "«один» — единственность, а не счёт")

console.log("— исключение действует только там, где названо —")
// 🛑 ПУТЬ ЗАПИСАН СЫРОЙ СТРОКОЙ, И ЭТО НЕ ПЕДАНТИЗМ: обычная строка с двумя обратными слэшами
// читается в JavaScript как \v — вертикальная табуляция, — и прибор проверял бы не тот путь.
// Первая редакция этого случая падала именно поэтому: врал ПРИБОР, а не сторож.
check(problemsIn("// два глагола", String.raw`\lib\verbs.mjs`, counts).length === 0, "исключение у verbs.mjs работает")
check(problemsIn("// два глагола", String.raw`\lib\other.mjs`, counts).length === 1, "и НЕ распространяется на соседей")

console.log(failed === 0 ? "\n✓ все случаи сошлись" : `\n🛑 не сошлось: ${failed}`)
process.exit(failed === 0 ? 0 : 1)
