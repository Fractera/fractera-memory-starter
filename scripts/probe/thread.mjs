#!/usr/bin/env node
//
// ПРИБОР 184 — НИТЬ РАЗБОРА: ПАМЯТЬ ВОЗВРАЩАЕТ ЕЁ ИМЯ И УМЕЕТ К НЕЙ ВЕРНУТЬСЯ.
//
// 🔒 ЧТО ЗДЕСЬ ИЗМЕРЯЕТСЯ, А ЧТО НЕТ. Не «принимается ли параметр», а три
// утверждения, каждое из которых можно опровергнуть:
//   ① у ответа, где память думала, есть имя нити;
//   ② присланное обратно имя продолжает ТУ ЖЕ нить, а не начинает новую;
//   ③ чужое имя даёт НАЗВАННЫЙ отказ, а не «модель ответила не по форме».
//
// 🛑 КАЖДЫЙ ПРОГОН ТРАТИТ КВОТУ ПОДПИСКИ ВЛАДЕЛЬЦА — ту же, которой живёт бот.
// Поэтому вызовов ровно три, и все короткие.

import { call, cleanup, fate, scoreboard } from "./_call.mjs"

const WHO = "probe-184"
const s = scoreboard("ПРИБОР 184 — нить разбора")

// ── ① ИМЯ НИТИ ПРИХОДИТ САМО, БЕЗ ПРОСЬБЫ ────────────────────────────────────
const first = await call("remember", { lang: "ru", text: "я говорю с вами по-русски", who: WHO })
const thread = first.data?.thread
s.say(first.data?.ok === true, "первый разбор прошёл", `${first.ms} мс`)
s.say(
  typeof thread === "string" && thread.length > 10,
  "имя нити пришло в ответе, хотя его не просили",
  String(thread),
)
s.say(
  !("params" in (first.data ?? {})),
  "о неприсланных параметрах ответ молчит — нить не попала в отчёт судеб",
)

// ── ② ПРИСЛАННОЕ ИМЯ ПРОДОЛЖАЕТ ТУ ЖЕ НИТЬ ───────────────────────────────────
const second = await call("remember", {
  lang: "ru",
  text: "и ещё я живу в Мадриде",
  thread,
  who: WHO,
})
s.say(second.data?.ok === true, "продолжение нити прошло", `${second.ms} мс`)
s.say(
  second.data?.thread === thread,
  "вернулось ТО ЖЕ имя нити, а не новое",
  `${second.data?.thread}`,
)
s.say(fate(second.data, "thread")?.state === "accepted", "судьба «thread» названа принятой")

// ── ③ ОТРИЦАНИЕ ИМЕЕТ СМЫСЛ ТОЛЬКО В НИТИ ────────────────────────────────────
// 🔒 ЭТО МЫСЛЬ ВЛАДЕЛЬЦА, СТАВШАЯ ПРАВИЛОМ: «если пользователь говорит
// опровержение предыдущего вывода, то без возможности вернуться к предыдущей
// цепочке это не имеет никакого смысла».
const denyNoThread = await call("remember", {
  deny: "это неверно, я живу не в Мадриде",
  lang: "ru",
  text: "уточняю про город",
  who: WHO,
})
const dn = fate(denyNoThread.data, "deny")
s.say(
  dn?.state === "not_supported",
  "НЕГАТИВНЫЙ: отрицание без нити — не поддержано",
  dn?.state ?? "строки нет",
)
s.say(
  Boolean(dn?.note) && dn.note.includes("thread"),
  "НЕГАТИВНЫЙ: сказано, ЧЕГО не хватает, а не просто «нельзя»",
  dn?.note ?? "—",
)

// ── ④ НЕГАТИВНЫЙ КОНТРОЛЬ: ЧУЖОЕ ИМЯ НИТИ ────────────────────────────────────
// 🔒 БЕЗ НЕГО ПРИБОР ДОКАЗЫВАЛ БЫ ТОЛЬКО УСПЕШНЫЙ ПУТЬ. Измерено 2026-09-11:
// чужой идентификатор даёт код выхода 1, ПУСТОЙ stdout и весь смысл в stderr.
// Разбор, ждущий JSON, назвал бы это «ответ не по форме».
const bogus = await call("remember", {
  lang: "ru",
  text: "проверка",
  thread: "00000000-0000-0000-0000-000000000000",
  who: WHO,
})
s.say(
  bogus.data?.refusal === "think-thread-unknown",
  "НЕГАТИВНЫЙ: чужая нить названа своим родом отказа",
  `${bogus.data?.refusal ?? bogus.data?.error ?? "—"}`,
)
s.say(
  String(bogus.data?.what_happened ?? "").includes("нити"),
  "НЕГАТИВНЫЙ: человеку сказано словами, что делать",
  String(bogus.data?.what_happened ?? "—"),
)
s.say(
  bogus.data?.refusal !== "think-answer-unusable",
  "НЕГАТИВНЫЙ: это НЕ «ответ не по форме» — иначе чинили бы модель вместо идентификатора",
)

await cleanup(WHO, [
  "person_who_owns_this_project",
  "person_who_owns_this_project__what_he_told_us_before",
])
console.log("")
console.log(`(убрано по метке who = ${WHO}; чужих строк прибор не трогает)`)

s.done("нить возвращается, продолжается и отвергается по имени")
