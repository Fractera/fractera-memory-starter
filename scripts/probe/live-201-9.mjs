async function call(verb, body, form) {
  const started = Date.now()
  const init = form
    ? { body: form, headers: { "x-memory-key": KEY }, method: "POST" }
    : { body: JSON.stringify(body), headers: { "content-type": "application/json", "x-memory-key": KEY }, method: "POST" }
  let json = null
  let status = 0
  try {
    const r = await fetch(`${BASE}/v1/${verb}`, init)
    status = r.status
    json = await r.json().catch(() => ({ raw: "not json" }))
  } catch (e) {
    json = { error: "unreachable", why: String(e.message) }
  }
  return { json, ms: Date.now() - started, status }
}

