function formFor(payload, names) {
  const form = new FormData()
  form.append("payload", JSON.stringify(payload))
  for (const name of names) {
    const type = name.endsWith(".png")
      ? "image/png"
      : name.endsWith(".pdf")
        ? "application/pdf"
        : name.endsWith(".csv")
          ? "text/csv"
          : name.endsWith(".json")
            ? "application/json"
            : name.endsWith(".md")
              ? "text/markdown"
              : "text/plain"
    form.append("files", new Blob([FILES[name]], { type }), name)
  }
  return form
}

