//
// ✗ ЧЕМ ОПЛАЧЕН: дверь слов без глагола легла на `/v1`, а проверка доступа смотрела на `/v1/` со
// слэшем. Адрес не подошёл под образец — и **отвечал всем без ключа**, `200`. Ни отказа, ни ошибки,
// ни строки в логе. Нашлось живым замером, потому что прибор всегда звал дверь С ключом.
//
// 🔒 ЗАКОН ШИРЕ СЛУЧАЯ: У НОВОГО АДРЕСА ДВА ВОПРОСА, А НЕ ОДИН — «работает ли» и «ЗАКРЫТ ЛИ».
// Первый проверяют всегда, второй почти никогда: он не мешает работе и виден только тому, кто
// нарочно позвал без ключа.
//
// 🔒 ПОЭТОМУ ЗДЕСЬ ПРОВЕРЯЕТСЯ ПРАВИЛО, А НЕ ЖИВАЯ ДВЕРЬ: список адресов берётся из ДОГОВОРА, и
// каждый прогоняется через ту же функцию, которой служба решает, пускать ли. Забытый адрес
// всплывает сразу, а не через месяц.

import { readFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { contract } from "../../contract.mjs"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const server = readFileSync(join(ROOT, "server.mjs"), "utf8")

let failed = 0
const check = (ok, what, got = "") => {
  if (!ok) failed++
  console.log(`${ok ? "✓" : "🛑"} ${what}${got ? ` → ${got}` : ""}`)
}

// Правило замка, снятое с самой службы: строка проверки читается из кода, а не переписывается сюда.
// 🛑 Перепиши мы её словами — прибор проверял бы СВОЁ представление о замке, а не замок.
const rule = /if \(path !== "\/v1" && !path\.startsWith\("\/v1\/"\)\) return true/.test(server)
check(rule, "замок стережёт и `/v1` без слэша, и всё под `/v1/`")

console.log("— каждый адрес договора попадает под замок —")
const paths = [
  ...contract().methods.map((m) => `/v1/${m.name}`),
  ...contract().catalogue.map((x) => x.path.replace(/^[A-Z]+ /, "").replace(/\{[^}]+\}/g, "abc")),
]
const locked = (p) => p === "/v1" || p.startsWith("/v1/")
for (const p of paths) {
  // `health` открыт намеренно: его зовут установщик и сторож, у которых ключа может не быть, и он
  // не говорит ничего о человеке. Это ИСКЛЮЧЕНИЕ с причиной, а не дыра.
  const open = p === "/v1/health"
  check(open || locked(p), `${p} — ${open ? "открыт намеренно" : "под замком"}`)
}

console.log("— негативный контроль: чужой адрес под замок НЕ попадает —")
for (const p of ["/ru/settings", "/v1x/remember", "/", "/v10/state"]) {
  check(!locked(p), `${p} — не наш адрес и замком не стережётся`)
}

console.log("— и сам счётчик не слеп —")
check(paths.length >= 5, "адресов в договоре найдено", String(paths.length))
check(locked("/v1") && locked("/v1/recall"), "правило признаёт оба вида нашего адреса")

console.log(failed === 0 ? "\n✓ все случаи сошлись" : `\n🛑 не сошлось: ${failed}`)
process.exit(failed === 0 ? 0 : 1)
